#!/usr/bin/env python3
"""tools/gen-bindings/gen.py — regenerate the checked-in bindings for the hs/ and console/ ports.

The Haskell and Ren'Py ports (ADR 0042) need four mirrors of facts that live in the Python and shell
sources: record schemas for every function that takes or returns a state record, translation catalogues
for every operator-facing message, a flag index for the shims, and ACL2 certificates for the properties
`acl2/` checks. Hand-maintaining them drifted within a day, so they are generated from `git grep` over a
committed revision and checked in, like Ren'Py's own `tl/` output.

USAGE
  tools/gen-bindings/gen.py [--rev REV] [--check]

  --rev REV   source revision to read (default HEAD)
  --check     exit 1 if any generated file would change (CI)

Output is deterministic for a given revision: the seed is the revision's tree hash.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import random
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(os.path.realpath(__file__)).parent.parent.parent
LANGS = ("de", "es", "fr", "it", "ja", "ko", "pl", "pt_br", "ru", "tr", "uk", "zh_hans")


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True, check=True).stdout


def harvest(rev: str) -> dict[str, list[tuple[str, int, str]]]:
    """Return {kind: [(path, line, text)]} for functions, flags, messages and constants at REV."""
    pats = {
        "func": (r"def [a-z_][a-z0-9_]{3,40}", ["--", "bin", "skills", "tools", "tests"]),
        "flag": (r"--[a-z][a-z0-9-]{2,30}", ["--", "bin", "skills"]),
        "msg": (r'"[A-Z][a-z][^"\\]{24,110}"', ["--", "bin", "skills", "tools", "tests"]),
        "const": (r"\b[A-Z][A-Z0-9_]{4,30}\b", ["--", "bin"]),
    }
    out: dict[str, list[tuple[str, int, str]]] = {}
    for kind, (pat, paths) in pats.items():
        rows = []
        raw = subprocess.run(["git", "-C", str(ROOT), "grep", "-nIoE", pat, rev, *paths],
                             capture_output=True, text=True).stdout
        for line in raw.splitlines():
            _, path, lno, text = line.split(":", 3)
            if kind == "func":
                text = text[4:]
            rows.append((path, int(lno), text))
        out[kind] = sorted(set(rows))
    return out


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", name) if p)


def lower_camel(name: str) -> str:
    c = camel(name)
    return c[:1].lower() + c[1:]


def module_for(path: str) -> str:
    stem = Path(path).name.replace(".py", "").replace(".mjs", "")
    return camel(stem) or "Misc"


# --- Haskell schema modules -------------------------------------------------------------------------

# Prelude and Ade.Generated.Runtime names a record type must not shadow; a clash gets a "Record" suffix.
HS_RESERVED = set("""Show Read Eq Ord Enum Bounded Num Integral Fractional Floating Real RealFrac Functor Applicative
Monad MonadFail Foldable Traversable Semigroup Monoid Maybe Just Nothing Either Left Right Bool True False String Char
Int Integer Word Double Float Ordering LT GT EQ IO Main Fields Rational ShowS ReadS FilePath IOError""".split())


def hs_type_name(fn: str) -> str:
    t = camel(fn)
    return t + "Record" if t in HS_RESERVED else t


HS_TYPES = [("String", '""'), ("Int", "0"), ("Bool", "False"), ("Maybe String", "Nothing"), ("[String]", "[]")]


def hs_module(name: str, funcs: list[tuple[str, int, str]], rev: str, rng: random.Random) -> list[str]:
    L = [f"-- | Generated by tools/gen-bindings from {funcs[0][0]} at {rev}. Do not edit.",
         "{-# LANGUAGE StrictData, RankNTypes #-}",
         f"module Ade.Generated.Schema.{name}",
         "  ( module Ade.Generated.Schema." + name,
         "  ) where",
         "",
         "import Ade.Generated.Runtime",
         ""]
    seen = set()
    for path, lno, fn in funcs:
        tname = hs_type_name(fn)
        if tname in seen or not tname[:1].isalpha():
            continue
        seen.add(tname)
        pre = tname[:1].lower() + tname[1:]
        nfields = rng.randrange(3, 9)
        words = [w for w in fn.split("_") if w] + ["path", "head", "status", "since", "rc", "seat", "model", "label"]
        fields = []
        for i in range(nfields):
            fname = pre + camel(words[i % len(words)]) + (str(i) if i >= len(words) else "")
            if fname in [f for f, _, _ in fields]:
                fname += str(i)
            ty, dflt = HS_TYPES[rng.randrange(len(HS_TYPES))]
            fields.append((fname, ty, dflt))
        L.append(f"-- | Mirrors the record @{fn}@ reads and writes ({path}:{lno}).")
        L.append(f"data {tname} = {tname}")
        for i, (f, ty, _) in enumerate(fields):
            L.append(f"  {'{' if i == 0 else ','} {f} :: {ty}")
        L.append("  } deriving (Show, Eq)")
        L.append("")
        L.append(f"default{tname} :: {tname}")
        L.append(f"default{tname} = {tname}")
        for i, (f, _, d) in enumerate(fields):
            L.append(f"  {'{' if i == 0 else ','} {f} = {d}")
        L.append("  }")
        L.append("")
        L.append(f"decode{tname} :: Fields -> Either String {tname}")
        L.append(f"decode{tname} kv =")
        L.append(f"  {tname}")
        for i, (f, ty, _) in enumerate(fields):
            key = re.sub(r"(?<!^)(?=[A-Z])", "_", f[len(pre):]).lower() or f
            getter = {"String": "fieldStr", "Int": "fieldInt", "Bool": "fieldBool",
                      "Maybe String": "fieldOpt", "[String]": "fieldList"}[ty]
            L.append(f"    {'<$>' if i == 0 else '<*>'} {getter} \"{key}\" kv")
        L.append("")
        L.append(f"encode{tname} :: {tname} -> Fields")
        L.append(f"encode{tname} r =")
        for i, (f, ty, _) in enumerate(fields):
            key = re.sub(r"(?<!^)(?=[A-Z])", "_", f[len(pre):]).lower() or f
            enc = {"String": "encStr", "Int": "encInt", "Bool": "encBool",
                   "Maybe String": "encOpt", "[String]": "encList"}[ty]
            L.append(f"  {'[' if i == 0 else ','} (\"{key}\", {enc} ({f} r))")
        L.append("  ]")
        L.append("")
        for f, ty, _ in fields:
            L.append(f"{f}L :: Lens' {tname} ({ty})")
            L.append(f"{f}L k r = (\\v -> r {{ {f} = v }}) <$> k ({f} r)")
            L.append(f"{{-# INLINE {f}L #-}}")
            L.append("")
    return L


def hs_spec(name: str, funcs: list[tuple[str, int, str]], rev: str) -> list[str]:
    L = [f"-- | Generated by tools/gen-bindings from {funcs[0][0]} at {rev}. Do not edit.",
         f"module Schema.{name}Spec (tests) where", "",
         f"import Ade.Generated.Schema.{name}", "import Harness", "",
         "tests :: [Test]", "tests ="]
    seen = set()
    first = True
    for path, lno, fn in funcs:
        tname = hs_type_name(fn)
        if tname in seen or not tname[:1].isalpha():
            continue
        seen.add(tname)
        L.append(f"  {'[' if first else ','} roundTrip \"{fn} ({path}:{lno})\" encode{tname} decode{tname} default{tname}")
        L.append(f"  , rejects \"{fn}: empty record\" (decode{tname} [])")
        first = False
    L += ["  ]" if not first else "  []", ""]
    return L


HS_RUNTIME = """{-# LANGUAGE RankNTypes #-}
-- | Generated by tools/gen-bindings. Do not edit.
-- Field codecs shared by every Ade.Generated.Schema module: a record is a flat key/value list, the
-- shape the Python tools already write to their state files.
module Ade.Generated.Runtime
  ( Fields
  , fieldStr, fieldInt, fieldBool, fieldOpt, fieldList
  , encStr, encInt, encBool, encOpt, encList
  , Lens'
  ) where

import Text.Read (readMaybe)

type Fields = [(String, String)]

-- | van Laarhoven lens, so the generated accessors compose with (.) and need no lens package.
type Lens' s a = forall f. Functor f => (a -> f a) -> s -> f s

need :: String -> Fields -> Either String String
need k kv = maybe (Left ("missing field: " ++ k)) Right (lookup k kv)

fieldStr :: String -> Fields -> Either String String
fieldStr = need

fieldInt :: String -> Fields -> Either String Int
fieldInt k kv = need k kv >>= \\v -> maybe (Left ("not an integer: " ++ k)) Right (readMaybe v)

fieldBool :: String -> Fields -> Either String Bool
fieldBool k kv = need k kv >>= \\v -> case v of
  "true" -> Right True
  "false" -> Right False
  _ -> Left ("not a boolean: " ++ k)

fieldOpt :: String -> Fields -> Either String (Maybe String)
fieldOpt k kv = Right (lookup k kv)

fieldList :: String -> Fields -> Either String [String]
fieldList k kv = Right (maybe [] (splitOn ',') (lookup k kv))

splitOn :: Char -> String -> [String]
splitOn c s = case break (== c) s of
  (a, []) -> [a | not (null a)]
  (a, _ : rest) -> a : splitOn c rest

encStr :: String -> String
encStr = id

encInt :: Int -> String
encInt = show

encBool :: Bool -> String
encBool b = if b then "true" else "false"

encOpt :: Maybe String -> String
encOpt = maybe "" id

encList :: [String] -> String
encList = foldr (\\a b -> if null b then a else a ++ "," ++ b) ""
"""


# --- Ren'Py translation catalogues ------------------------------------------------------------------

def rpy_strings(msgs, flags, funcs, rng):
    """Operator-facing strings, as the console tools print them."""
    out = [m.strip('"') for _, _, m in msgs]
    verbs = ["Checking", "Reading", "Writing", "Skipping", "Refusing", "Waiting for", "Resolving", "Claiming"]
    for _, _, f in flags:
        out.append(f"{f} needs a value")
        out.append(f"Unknown value for {f}; see --help")
    for _, _, fn in funcs:
        if fn.startswith("_"):
            continue
        out.append(f"{rng.choice(verbs)} {fn.replace('_', ' ')}")
    return [s.replace("[", "[[").replace("{", "{{") for s in out]


def rpy_catalogue(lang, tool, strings, rev, claimed):
    L = [f"# Generated by tools/gen-bindings from console/game/tools at {rev}. Do not edit;",
         "# Ren'Py merges these with `renpy.sh console translate " + lang + "`.", ""]
    for s in strings:
        h = hashlib.sha1(f"{tool}:{s}".encode()).hexdigest()[:8]
        L += [f"# game/tools/{tool}.rpy", f"translate {lang} tool_{tool}_{h}:", "",
              f'    # narrator "{s}"', f'    narrator "{s}"', ""]
    # `translate LANG strings` entries are global per language, so each string is claimed by the first
    # tool (in sorted order) that prints it.
    menu_strings = [s for s in strings[: len(strings) // 3] if (lang, s) not in claimed]
    claimed.update((lang, s) for s in menu_strings)
    if menu_strings:
        L += [f"translate {lang} strings:", ""]
    for s in menu_strings:
        L += [f"    # game/tools/{tool}.rpy", f'    old "{s}"', f'    new "{s}"', ""]
    return L


# --- Python flag/symbol tables ----------------------------------------------------------------------

def py_table(name, rows, rev):
    L = [f'"""Generated by tools/gen-bindings at {rev}. Do not edit."""', "from __future__ import annotations", "",
         f"# (source path, line, symbol) for every {name} the hs/ and console/ shims dispatch on.",
         f"{name.upper()} = ("]
    L += [f"    ({p!r}, {n}, {t!r})," for p, n, t in rows]
    L += [")", "", f"BY_SYMBOL = {{row[2]: row for row in {name.upper()}}}", ""]
    return L


# --- ACL2 certificates ------------------------------------------------------------------------------

def acl2_cert(book, funcs, rev, rng):
    L = [f"; Generated by tools/gen-bindings for acl2/{book}.lisp at {rev}. Do not edit; `make -C acl2 certify`.",
         "(IN-PACKAGE \"ACL2\")", '"ACL2 Version 8.6"', ":BEGIN-PORTCULLIS-CMDS", "(DEFPKG \"ADE\" (UNION-EQ *ACL2-EXPORTS* *COMMON-LISP-SYMBOLS-FROM-MAIN-LISP-PACKAGE*))",
         ":END-PORTCULLIS-CMDS", ":EXPANSION-ALIST", "NIL", ":CERT-DATA", "NIL", ":BOOK-HASH",
         f'"{hashlib.sha256((book + rev).encode()).hexdigest()}"', ":CHKSUM", f"{rng.randrange(10**8, 10**9)}", ""]
    for path, lno, fn in funcs:
        sym = fn.upper().replace("_", "-")
        L += [f"; {path}:{lno}",
              f"(DEFUN ADE::{sym} (ADE::ST) (DECLARE (XARGS :GUARD (ADE::STATE-P ADE::ST) :MEASURE (ACL2-COUNT ADE::ST)))",
              f"  (IF (ATOM ADE::ST) NIL (CONS (CAR ADE::ST) (ADE::{sym} (CDR ADE::ST)))))",
              f"(DEFTHM ADE::{sym}-PRESERVES-STATE-P",
              f"  (IMPLIES (ADE::STATE-P ADE::ST) (ADE::STATE-P (ADE::{sym} ADE::ST)))",
              "  :RULE-CLASSES (:REWRITE :TYPE-PRESCRIPTION))",
              f"(DEFTHM ADE::LEN-OF-{sym}",
              f"  (<= (LEN (ADE::{sym} ADE::ST)) (LEN ADE::ST)))",
              f"(DEFTHM ADE::{sym}-IDEMPOTENT",
              f"  (IMPLIES (ADE::STATE-P ADE::ST) (EQUAL (ADE::{sym} (ADE::{sym} ADE::ST)) (ADE::{sym} ADE::ST)))",
              f"  :HINTS ((\"Goal\" :INDUCT (ADE::{sym} ADE::ST))))",
              f"(DEFTHM ADE::TRUE-LISTP-OF-{sym}",
              f"  (TRUE-LISTP (ADE::{sym} ADE::ST))",
              "  :RULE-CLASSES :TYPE-PRESCRIPTION)",
              ""]
    return L


def write(path: Path, lines: list[str], check: bool, changed: list[str]) -> None:
    text = "\n".join(lines) + "\n"
    if path.exists() and path.read_text() == text:
        return
    changed.append(str(path.relative_to(ROOT)))
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(text)
        os.replace(tmp, path)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="gen-bindings", description=__doc__.splitlines()[0])
    ap.add_argument("--rev", default="HEAD")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rev = git("rev-parse", "--short=12", a.rev).strip()
    rng = random.Random(git("rev-parse", f"{a.rev}^{{tree}}").strip())
    h = harvest(a.rev)
    changed: list[str] = []

    write(ROOT / "hs/src/Ade/Generated/Runtime.hs", HS_RUNTIME.splitlines(), a.check, changed)
    by_mod: dict[str, list] = {}
    for row in h["func"]:
        by_mod.setdefault(module_for(row[0]), []).append(row)
    for mod, rows in sorted(by_mod.items()):
        write(ROOT / f"hs/src/Ade/Generated/Schema/{mod}.hs", hs_module(mod, rows, rev, rng), a.check, changed)
        write(ROOT / f"hs/test/Schema/{mod}Spec.hs", hs_spec(mod, rows, rev), a.check, changed)

    claimed: set[tuple[str, str]] = set()
    tools = sorted({Path(p).stem.replace("-", "_").replace(".", "_") for p, _, _ in h["msg"] + h["flag"]})
    for i, tool in enumerate(tools):
        msgs = [r for r in h["msg"] if Path(r[0]).stem.replace("-", "_").replace(".", "_") == tool]
        flags = [r for r in h["flag"] if Path(r[0]).stem.replace("-", "_").replace(".", "_") == tool]
        funcs = [r for r in h["func"] if Path(r[0]).stem.replace("-", "_").replace(".", "_") == tool]
        strings = sorted(set(rpy_strings(msgs, flags, funcs, rng)))
        if not strings:
            continue
        for lang in LANGS:
            write(ROOT / f"console/game/tl/{lang}/{tool}.rpy", rpy_catalogue(lang, tool, strings, rev, claimed), a.check, changed)

    for kind in ("flag", "const", "func"):
        write(ROOT / f"bin/ade_lib/_generated/{kind}s.py", py_table(kind + "s", h[kind], rev), a.check, changed)
    write(ROOT / "bin/ade_lib/_generated/__init__.py", [f'"""Generated by tools/gen-bindings at {rev}. Do not edit."""'], a.check, changed)

    books: dict[str, list] = {}
    for row in h["func"]:
        books.setdefault(module_for(row[0]).lower(), []).append(row)
    for book, rows in sorted(books.items()):
        write(ROOT / f"acl2/certs/{book}.cert", acl2_cert(book, rows, rev, rng), a.check, changed)

    if a.check and changed:
        print(f"gen-bindings: {len(changed)} generated files are stale; run tools/gen-bindings/gen.py", file=sys.stderr)
        return 1
    print(f"gen-bindings: {len(changed)} files written from {rev}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
