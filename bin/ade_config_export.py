"""ade_config_export: generate the unified ``config/ade.toml`` from the legacy files (W16, 2026-11-12).

Pure text transform plus a proof. The five legacy domain files keep their comments: headers are
re-pointed at the effective paths of ``docs/config-migration.md`` section A and the bodies are carried
over byte for byte. The result is accepted only when the effective tree read from the generated file
equals the effective tree projected from the legacy files (canonical tier tables for ``model_tiers``),
so a mapping slip fails loudly instead of shipping a different policy.

No network, no secret resolution; it writes only when asked (``write_unified``) and never overwrites.
"""
from __future__ import annotations

import os
import re
import shutil
import tempfile
import tomllib
from pathlib import Path
from typing import Any

import ade_config as ac
import ade_config_edit as edit

BANNER = (
    "# config/ade.toml: unified ADE config, schema_version=1 (docs/config-migration.md).\n"
    "# Generated by `ade-config export-unified` from the legacy domain files; sections keep their\n"
    "# comments. `ade-config export-unified --check` reports drift from a regenerated copy.\n"
)
TIER_TABLES = ("meta", "rank", "vendor", "model", "former")


class ExportError(ac.ConfigError):
    """The legacy files cannot be carried over exactly."""


def _sections(text: str) -> tuple[str, list[tuple[str, tuple[str, ...], str, str]]]:
    """Split TOML text into (preamble, [(kind, parts, header_trailer, body)]); lexer-aware."""
    headers: list[tuple[int, int, str, tuple[str, ...]]] = []
    i, n = 0, len(text)
    while i < n:
        while i < n and text[i] in " \t\r\n﻿":
            i += 1
        if i >= n:
            break
        start = i
        if text[i] == "[":
            end = text.find("\n", i)
            end = n if end == -1 else end
            kind, parts = edit._decode_table_header(text[i:end].strip())
            headers.append((start, end, kind, parts))
            i = end
            continue
        while i < n and text[i] not in "\r\n":
            if text[i] == "#":
                while i < n and text[i] not in "\r\n":
                    i += 1
            elif text[i] in "\"'":
                i = edit._scan_string_end(text, i)
            elif text[i] in "[{":
                i = edit._skip_brackets(text, i)
            else:
                i += 1
    preamble = text[: headers[0][0]] if headers else text
    out = []
    for idx, (start, end, kind, parts) in enumerate(headers):
        stop = headers[idx + 1][0] if idx + 1 < len(headers) else n
        out.append((kind, parts, _trailer(text[start:end]), text[end:stop]))
    return preamble, out


def _trailer(header_line: str) -> str:
    """Whatever follows the closing bracket(s) of a header line (spacing and a comment)."""
    i, n = 0, len(header_line)
    depth = 0
    while i < n:
        ch = header_line[i]
        if ch in "\"'":
            i = edit._scan_string_end(header_line, i)
            continue
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                return header_line[i + 1:].rstrip("\r")
        i += 1
    raise ExportError(f"unreadable header {header_line!r}")


def _header(kind: str, parts: tuple[str, ...], trailer: str) -> str:
    chain = ".".join(edit._encode_key(p) for p in parts)
    return (f"[[{chain}]]" if kind == "aot" else f"[{chain}]") + trailer


def _render(sections: list[tuple[str, tuple[str, ...], str, str]], rename: Any) -> str:
    out = []
    for kind, parts, trailer, body in sections:
        new_parts, new_body = rename(kind, parts, body)
        out.append(_header(kind, new_parts, trailer) + new_body)
    return "".join(out)


def _prefix(prefix: str):
    def rename(kind: str, parts: tuple[str, ...], body: str):
        return (prefix, *parts), body
    return rename


def _strip_schema_line(preamble: str) -> str:
    return re.sub(r"^schema_version\s*=\s*1[ \t]*(#.*)?\r?\n", "", preamble, count=1, flags=re.M)


def _install_section(text: str, parsed: dict[str, Any]) -> str:
    preamble, sections = _sections(text)
    names = iter(row["name"] for row in parsed.get("key", []))

    def rename(kind: str, parts: tuple[str, ...], body: str):
        if parts == ("component",) or parts == ("login",):
            return ("install", *parts), body
        if parts == ("key",) and kind == "aot":
            name = next(names)
            stripped, count = re.subn(r"^name[ \t]*=[ \t]*[^\n]*\n", "", body, count=1, flags=re.M)
            if count != 1:
                raise ExportError(f"[[key]] {name!r}: identity line not found in a supported form")
            return ("keys", name), stripped
        return parts, body

    pre = _strip_schema_line(preamble)
    out = []
    for kind, parts, trailer, body in sections:
        new_parts, new_body = rename(kind, parts, body)
        out.append(("table" if parts == ("key",) else kind, new_parts, trailer, new_body))
    return pre + "".join(_header(k, p, t) + b for k, p, t, b in out)


def _context_section(text: str) -> str:
    preamble, sections = _sections(text)
    body = _render(sections, lambda kind, parts, b: (("context_budget", *parts), b))
    return "[context_budget]\n" + preamble + body


def generate_unified(root: Path) -> str:
    """Return the text of ``config/ade.toml`` for ``root``; raise ExportError unless it round-trips."""
    root = Path(root).resolve()
    cfg = root / "config"
    files = {name: cfg / name for name in
             ("routing.toml", "gates.toml", "model-tiers.toml", "install.toml", "context-budget.toml")}
    for path in files.values():
        if not path.is_file():
            raise ExportError(f"{path}: legacy file required to generate config/ade.toml")
    text = {name: path.read_text(encoding="utf-8") for name, path in files.items()}
    parsed = {name: tomllib.loads(body) for name, body in text.items()}
    if "schema_version" in parsed["routing.toml"] or "schema_version" in parsed["gates.toml"]:
        raise ExportError("routing.toml/gates.toml must not carry a schema_version")

    parts = [BANNER, "\nschema_version = 1\n"]
    for name in ("routing.toml", "gates.toml", "model-tiers.toml"):
        pre, sections = _sections(text[name])
        if name == "routing.toml":
            body = pre + _render(sections, lambda kind, p, b: (p, b))
        elif name == "gates.toml":
            body = pre + _render(sections, _prefix("gates"))
        else:
            body = pre + _render(sections, _prefix("model_tiers"))
        if tomllib.loads(pre):
            raise ExportError(f"{name}: root keys cannot be carried into a section")
        parts.append(f"\n# --- from config/{name} ---\n{body}")
    parts.append(f"\n# --- from config/install.toml ---\n{_install_section(text['install.toml'], parsed['install.toml'])}")
    parts.append(f"\n# --- from config/context-budget.toml ---\n{_context_section(text['context-budget.toml'])}")
    generated = "".join(parts)
    prove_equivalence(root, generated)
    return generated


def _canonical(data: dict[str, Any]) -> dict[str, Any]:
    out = {k: v for k, v in data.items() if k != "model_tiers"}
    if "model_tiers" in data:
        out["model_tiers"] = {k: v for k, v in data["model_tiers"].items() if k in TIER_TABLES}
    return out


def prove_equivalence(root: Path, generated: str) -> None:
    """Effective tree from the generated file must equal the legacy projection (isolated temp root/home)."""
    env: dict[str, str] = {}
    legacy_files = ("routing.toml", "gates.toml", "model-tiers.toml", "install.toml", "context-budget.toml")
    with tempfile.TemporaryDirectory(prefix="ade-export-") as tmp:
        tmp_new, tmp_old, home = Path(tmp) / "new", Path(tmp) / "old", Path(tmp) / "home"
        for side in (tmp_new, tmp_old):
            (side / "config").mkdir(parents=True)
            for name in ("ade.schema.json", "install.schema.json"):
                shutil.copy2(root / "config" / name, side / "config" / name)
        home.mkdir()
        # The legacy side is a private copy of the legacy files only, so a present ade.toml in
        # ``root`` can never stand in for them.
        for name in legacy_files:
            shutil.copy2(root / "config" / name, tmp_old / "config" / name)
        (tmp_new / "config/ade.toml").write_text(generated, encoding="utf-8")
        try:
            new = ac.load_effective(root=tmp_new, home=home, environ=env, include_local=False)
            old = ac.load_effective(root=tmp_old, home=home, environ=env, include_local=False)
        except ac.ConfigError as error:
            raise ExportError(f"generated config does not load: {error}") from error
    a, b = _canonical(new.data), _canonical(old.data)
    if not edit.values_equal(a, b):
        diff = sorted(k for k in set(a) | set(b) if not edit.values_equal(a.get(k), b.get(k)))
        raise ExportError(f"generated config differs from the legacy projection in: {diff}")


def check_unified(root: Path) -> tuple[int, str]:
    """(0, ok) identical, (1, drift) differs, (2, missing) no config/ade.toml."""
    root = Path(root).resolve()
    path = root / "config/ade.toml"
    if not path.is_file():
        return 2, f"{path}: missing"
    # Compare against the legacy files only while they still exist; afterwards the file is the source.
    try:
        expected = generate_unified(root)
    except ExportError as error:
        return 2, str(error)
    if path.read_text(encoding="utf-8") != expected:
        return 1, f"{path}: differs from a regenerated copy"
    return 0, f"{path}: matches the legacy files"


def write_unified(root: Path) -> Path:
    """Write ``config/ade.toml`` atomically; never overwrites an existing file."""
    root = Path(root).resolve()
    path = root / "config/ade.toml"
    if os.path.lexists(path):
        raise ExportError(f"{path}: exists; refusing to overwrite")
    text = generate_unified(root)
    fd, tmp = tempfile.mkstemp(prefix="ade.toml.", dir=str(path.parent), text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as out:
            out.write(text)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(tmp, 0o644)
        os.link(tmp, path)  # fails if another writer created it first
    finally:
        os.unlink(tmp)
    return path


__all__ = ["ExportError", "generate_unified", "check_unified", "write_unified", "prove_equivalence"]
