class SchedError(Exception):
    def __init__(self, code: int, msg: str):
        super().__init__(msg)
        self.code = code


# -- the job ---------------------------------------------------------------------------------------------------------

def default_subst(ade: str | os.PathLike[str] | None = None, env: Mapping[str, str] | None = None) -> dict[str, str]:
    """The placeholders every installer fills the same way: the checkout and the home directory."""
    env = os.environ if env is None else env
    root = os.path.realpath(ade) if ade else str(REPO)
    home = env.get("HOME") or str(Path.home())
    return {"__ADE__": root, "@ADE@": root, "__HOME__": home, "@HOME@": home}


def is_linked_worktree(path: str | os.PathLike[str]) -> bool:
    """True when `path` is a linked git worktree (git-common-dir != git-dir): its `.git` is a file naming a gitdir that has
    a `commondir`. A submodule's gitdir has none. Read from the files, no git process."""
    dotgit = Path(path) / ".git"
    try:
        if not dotgit.is_file():
            return False
        line = dotgit.read_text().strip()
    except OSError:
        return False
    if not line.startswith("gitdir:"):
        return False
    gitdir = Path(line[len("gitdir:"):].strip())
    if not gitdir.is_absolute():
        gitdir = Path(path) / gitdir
    return (gitdir / "commondir").exists()


def _fill(obj: Any, rx: re.Pattern[str] | None, subst: Mapping[str, str]) -> Any:
    """One pass per string, so a filled value is never filled again (--set __STATE__=__HOME__/x stays literal)."""
    if isinstance(obj, str):
        return rx.sub(lambda m: subst[m.group(0)], obj) if rx else obj
    if isinstance(obj, dict):
        return {k: _fill(v, rx, subst) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_fill(v, rx, subst) for v in obj]
    return obj


def _strings(obj: Any) -> list[str]:
    if isinstance(obj, str):
        return [obj]
    if isinstance(obj, dict):
        return [s for k, v in obj.items() for s in (*_strings(k), *_strings(v))]
    if isinstance(obj, list):
        return [s for v in obj for s in _strings(v)]
    return []


def _clean(value: str, what: str) -> str:
    if "\n" in value or "\r" in value or "\0" in value:
        raise SchedError(EX_USAGE, f"{what} contains a newline or NUL: {value!r}")
    return value


def _bool(d: Mapping[str, Any], key: str) -> bool:
    v = d.get(key, False)
    if not isinstance(v, bool):
        raise SchedError(EX_USAGE, f"{key} must be a boolean, not {v!r}")
    return v


def _abs(d: Mapping[str, Any], key: str) -> str | None:
    v = d.get(key)
    if v is None:
        return None
    if not isinstance(v, str) or not os.path.isabs(v):
        raise SchedError(EX_USAGE, f"{key} must be an absolute path, not {v!r}")
    return _clean(v, key)


@dataclass(frozen=True)
class Job:
    label: str
    argv: tuple[str, ...]
    env: dict[str, str] = field(default_factory=dict)
    cwd: str | None = None
    interval: int | None = None
    calendar: tuple[dict[str, int], ...] = ()
    run_at_load: bool = False
    keep_alive: bool | dict[str, Any] = False
    stdout: str | None = None
    stderr: str | None = None
    nice: int | None = None
    low_io: bool = False
    process_type: str | None = None
    kill_mode: str | None = None          # systemd KillMode; None: `process` for a oneshot, systemd's default when supervised
    raw: dict[str, Any] = field(default_factory=dict, compare=False)
    source: str = "<dict>"
    worktree: str | None = None           # set when __ADE__ defaulted into a linked worktree: install refuses (exit 2)

    @classmethod
    def from_plist(cls, path: str | os.PathLike[str], subst: Mapping[str, str] | None = None, *,
                   ade: str | os.PathLike[str] | None = None, kill_mode: str | None = None) -> Job:
        p = Path(path)
        try:
            data = p.read_bytes()
            if not data.startswith(b"bplist"):
                # Comments carry no data, and three checked-in plists (2026-11-04) have `--` inside one ("reap --install"),
                # which XML forbids and expat rejects while launchd accepts it. Placeholders are NOT touched here.
                data = re.sub(rb"<!--.*?-->", b"", data, flags=re.DOTALL)
            d = plistlib.loads(data)
        except Exception as e:   # OSError, plistlib.InvalidFileException, xml.parsers.expat.ExpatError
            raise SchedError(EX_USAGE, f"cannot read plist {p}: {e}") from e
        if not isinstance(d, dict):
            raise SchedError(EX_USAGE, f"{p}: the plist's root is not a dict")
        return cls.from_dict(d, source=str(p), subst=subst, ade=ade, kill_mode=kill_mode)

    @classmethod
    def from_dict(cls, d: Mapping[str, Any], source: str = "<dict>", subst: Mapping[str, str] | None = None, *,
                  ade: str | os.PathLike[str] | None = None, kill_mode: str | None = None) -> Job:
        """Fill default_subst(ade) then `subst` (which wins) into a copy of `d`, and validate it."""
        source = source.replace("\n", "?").replace("\r", "?")
        full = {**default_subst(ade), **(subst or {})}
        rx = re.compile("|".join(re.escape(k) for k in sorted(full, key=len, reverse=True))) if full else None
        uses_ade = any(k in s for s in _strings(d) for k in ("__ADE__", "@ADE@"))
        raw = _fill(dict(d), rx, full)
        left = {m for s in _strings(raw) for m in PLACEHOLDER_RE.findall(s)}
        if left:
            raise SchedError(EX_USAGE, f"{source}: unfilled placeholder(s) {', '.join(sorted(left))}; pass --set KEY=VALUE")
        worktree = None
        if uses_ade and ade is None and full["__ADE__"] == str(REPO) and is_linked_worktree(REPO):
            worktree = str(REPO)
        label = raw.get("Label")
        if not isinstance(label, str) or not LABEL_RE.fullmatch(label):
            raise SchedError(EX_USAGE, f"{source}: Label must match {LABEL_RE.pattern}, not {label!r}")
        args = raw.get("ProgramArguments")
        prog = raw.get("Program")
        if args is not None and (not isinstance(args, list) or not args or not all(isinstance(a, str) for a in args)):
            raise SchedError(EX_USAGE, f"{source}: ProgramArguments must be a non-empty list of strings")
        if prog is not None and not isinstance(prog, str):
            raise SchedError(EX_USAGE, f"{source}: Program must be a string")
        if prog:
            argv = [prog, *(args[1:] if args else [])]
        elif args:
            argv = list(args)
        else:
            raise SchedError(EX_USAGE, f"{source}: no ProgramArguments or Program")
        if not os.path.isabs(argv[0]):
            raise SchedError(EX_USAGE, f"{source}: the program must be an absolute path, not {argv[0]!r}")
        for a in argv:
            _clean(a, "an argument")
        env = raw.get("EnvironmentVariables", {})
        if not isinstance(env, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in env.items()):
            raise SchedError(EX_USAGE, f"{source}: EnvironmentVariables must map strings to strings")
        for k, v in env.items():
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k):
                raise SchedError(EX_USAGE, f"{source}: bad environment variable name {k!r}")
            if SECRET_RE.search(k):
                raise SchedError(EX_USAGE, f"{source}: EnvironmentVariables {k} looks like a secret; a secret never goes "
                                           f"into a unit file or crontab (fetch it at run time: sudo-secretspec get)")
            _clean(v, f"EnvironmentVariables {k}")
        interval = raw.get("StartInterval")
        if interval is not None and (isinstance(interval, bool) or not isinstance(interval, int) or interval <= 0):
            raise SchedError(EX_USAGE, f"{source}: StartInterval must be a positive integer, not {interval!r}")
        cal = raw.get("StartCalendarInterval")
        cals = [] if cal is None else [cal] if isinstance(cal, dict) else cal
        if not isinstance(cals, list):
            raise SchedError(EX_USAGE, f"{source}: StartCalendarInterval must be a dict or a list of dicts")
        for c in cals:
            if not isinstance(c, dict):
                raise SchedError(EX_USAGE, f"{source}: StartCalendarInterval entries must be dicts")
            for k, v in c.items():
                lo_hi = CAL_RANGES.get(k)
                if lo_hi is None:
                    raise SchedError(EX_USAGE, f"{source}: unknown StartCalendarInterval key {k!r}")
                if isinstance(v, bool) or not isinstance(v, int) or not lo_hi[0] <= v <= lo_hi[1]:
                    raise SchedError(EX_USAGE, f"{source}: StartCalendarInterval {k} out of range {lo_hi}: {v!r}")
        ka = raw.get("KeepAlive", False)
        if not isinstance(ka, (bool, dict)):
            raise SchedError(EX_USAGE, f"{source}: KeepAlive must be a boolean or a dict")
        nice = raw.get("Nice")
        if nice is not None and (isinstance(nice, bool) or not isinstance(nice, int) or not -20 <= nice <= 19):
            raise SchedError(EX_USAGE, f"{source}: Nice must be an integer in -20..19")
        pt = raw.get("ProcessType")
        if pt is not None and not isinstance(pt, str):
            raise SchedError(EX_USAGE, f"{source}: ProcessType must be a string")
        km = kill_mode if kill_mode is not None else raw.get("KillMode")
        if km is not None and km not in KILL_MODES:
            raise SchedError(EX_USAGE, f"{source}: KillMode must be one of {', '.join(KILL_MODES)}, not {km!r}")
        return cls(label=label, argv=tuple(argv), env=dict(env), cwd=_abs(raw, "WorkingDirectory"), interval=interval,
                   calendar=tuple(dict(c) for c in cals), run_at_load=_bool(raw, "RunAtLoad"), keep_alive=ka,
                   stdout=_abs(raw, "StandardOutPath"), stderr=_abs(raw, "StandardErrorPath"), nice=nice,
                   low_io=_bool(raw, "LowPriorityIO"), process_type=pt, kill_mode=km, raw=raw, source=source,
                   worktree=worktree)

    @property
    def ignored_keys(self) -> list[str]:
        return sorted(k for k in self.raw if k not in KNOWN_KEYS)

    @property
    def supervised(self) -> bool:
        return self.keep_alive is not False and self.keep_alive != {}

    @property
    def effective_nice(self) -> int | None:
        if self.nice is not None:
            return self.nice
        return 10 if self.process_type == "Background" else None

    @property
    def effective_kill_mode(self) -> str | None:
        """launchd leaves a job's setsid-detached children alive (bin/deadline's sweep); systemd's default
        control-group mode would kill them when ExecStart exits. So a oneshot defaults to `process`."""
        if self.kill_mode:
            return self.kill_mode
        return None if self.supervised else "process"


# -- rendering -------------------------------------------------------------------------------------------------------

def _sd_pct(s: str) -> str:
    return s.replace("%", "%%")


def _sd_inner(s: str, dollar: bool) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return s.replace("$", "$$") if dollar else s


def _sd_quote(s: str) -> str:
    return f'"{_sd_inner(s, dollar=True)}"'


def _header(job: Job, comment: str = "#") -> str:
    return f"{comment} {GENERATED} from {job.source}; edit the plist"


def _keep_alive_restart(job: Job) -> tuple[str, list[str]]:
    ka = job.keep_alive
    if ka is True:
        return "always", []
    assert isinstance(ka, dict)
    notes = [f"KeepAlive key {k} has no systemd equivalent; ignored" for k in ka if k not in ("SuccessfulExit", "Crashed")]
    if ka.get("SuccessfulExit") is False:
        return "on-failure", notes
    if ka.get("SuccessfulExit") is True:
        return "on-success", notes
    if ka.get("Crashed") is True:
        return "on-abnormal", notes
    return "always", notes


def _oncalendar(c: Mapping[str, int]) -> list[str]:
    """OnCalendar= values for one StartCalendarInterval dict. launchd (like cron) fires when EITHER Day or Weekday matches
    if both are given, while one systemd expression would need both: that pair becomes two expressions."""
    def two(k: str) -> str:
        return f"{c[k]:02d}" if k in c else "*"
    days = ("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")

    def expr(weekday: bool, day: bool) -> str:
        dow = f"{days[c['Weekday'] % 7]} " if weekday and "Weekday" in c else ""
        dom = two("Day") if day else "*"
        return f"{dow}*-{two('Month')}-{dom} {two('Hour')}:{two('Minute')}:00"
    if "Weekday" in c and "Day" in c:
        return [expr(True, False), expr(False, True)]
    return [expr(True, True)]


def _calendar_period(c: Mapping[str, int]) -> int:
    """The shortest gap between two firings of one calendar entry, capped at a day (a coarse bound for the start timeout)."""
    if "Minute" not in c:
        return 60
    if "Hour" not in c:
        return 3600
    return 86400


def start_timeout(job: Job) -> int | None:
    """TimeoutStartSec for a oneshot: max(3 x StartInterval, 300 s); a calendar job gets max(its shortest gap, 300 s), so a
    hung run never blocks the timer forever. None for a RunAtLoad-only job (it runs once) and a supervised one."""
    if job.supervised:
        return None
    cands = []
    if job.interval is not None:
        cands.append(max(3 * job.interval, 300))
    cands += [max(_calendar_period(c), 300) for c in job.calendar]
    return min(cands) if cands else None


def _path_entries(job: Job) -> list[str]:
    return [p for p in job.env.get("PATH", "").split(":") if p]


def _common_notes(job: Job, backend: str) -> list[str]:
    notes = [f"{job.label}: plist key {k} is not mapped on {backend}; ignored" for k in job.ignored_keys]
    if job.process_type and job.process_type != "Background" and backend == "systemd":
        notes.append(f"{job.label}: ProcessType={job.process_type} has no systemd equivalent; ignored")
    return notes


def render_systemd(job: Job, version: int | None = None) -> tuple[dict[str, str], list[str]]:
    """{"LABEL.service": text, "LABEL.timer": text (only for a timed job)}, notes. `version` is systemd's (None: assume
    240 or later, where StandardOutput=append: exists)."""
    notes = _common_notes(job, "systemd")
    timed = job.interval is not None or bool(job.calendar)
    if not (timed or job.run_at_load or job.supervised):
        raise SchedError(EX_USAGE, f"{job.source}: no StartInterval, StartCalendarInterval, RunAtLoad or KeepAlive: nothing to schedule")
    svc = [_header(job), "[Unit]", f"Description={_sd_pct(job.label)} (ade-sched)", "", "[Service]"]
    if job.supervised:
        restart, more = _keep_alive_restart(job)
        notes += [f"{job.label}: {n}" for n in more]
        svc += ["Type=simple", f"Restart={restart}", "RestartSec=10s"]
        if timed:
            notes.append(f"{job.label}: KeepAlive with a schedule: the timer also starts the supervised service")
    else:
        svc.append("Type=oneshot")
        to = start_timeout(job)
        if to is not None:
            svc.append(f"TimeoutStartSec={to}s")
    if job.effective_kill_mode:
        svc.append(f"KillMode={job.effective_kill_mode}")
    svc.append("ExecStart=" + " ".join(_sd_quote(a) for a in job.argv))
    if job.cwd:
        svc.append(f"WorkingDirectory={_sd_pct(job.cwd)}")
    env = dict(job.env)
    if "PATH" not in env:
        env = {"PATH": "", **env}
    for k, v in env.items():
        if k == "PATH":   # plist PATHs are Mac paths: ~/.local/bin (%h, systemd expands it) and the system dirs first
            rest = [p for p in _path_entries(job) if p not in PATH_PREFIX]
            val = ":".join(["%h/.local/bin", *PATH_PREFIX, *(_sd_inner(p, dollar=False) for p in rest)])
            svc.append(f'Environment="PATH={val}"')
        else:
            svc.append(f'Environment="{_sd_inner(f"{k}={v}", dollar=False)}"')
    mode = "append"
    if version is not None and version < 240:
        mode = "file" if version >= 236 else ""
        notes.append(f"{job.label}: systemd {version} has no StandardOutput=append: (240+); "
                     + ("using file:, which truncates the log at each run" if mode else "output goes to the journal"))
    if mode and job.stdout:
        svc.append(f"StandardOutput={mode}:{_sd_pct(job.stdout)}")
    if mode and job.stderr:
        svc.append(f"StandardError={mode}:{_sd_pct(job.stderr)}")
    if job.effective_nice is not None:
        svc.append(f"Nice={job.effective_nice}")
    if job.low_io:
        svc.append("IOSchedulingClass=idle")
    if job.supervised or (job.run_at_load and not timed):
        svc += ["", "[Install]", "WantedBy=default.target"]
    files = {f"{job.label}.service": "\n".join(svc) + "\n"}
    if timed:
        tim = [_header(job), "[Unit]", f"Description={_sd_pct(job.label)} timer (ade-sched)", "", "[Timer]",
               f"Unit={job.label}.service"]
        if job.interval is not None:
            n = job.interval
            tim += [f"OnActiveSec={1 if job.run_at_load else n}s", f"OnUnitActiveSec={n}s"]
        elif job.run_at_load:
            tim.append("OnActiveSec=1s")
        for c in job.calendar:
            tim += [f"OnCalendar={e}" for e in _oncalendar(c)]
        tim.append("AccuracySec=1s")   # systemd's default is 1 min: a 60 s sweep would drift to 2 min
        if job.calendar:
            tim.append("Persistent=true")
        tim += ["", "[Install]", "WantedBy=timers.target"]
        files[f"{job.label}.timer"] = "\n".join(tim) + "\n"
    return files, notes


def _cron_interval(n: int) -> tuple[str, str | None]:
    """A StartInterval of 60 s or more as a cron schedule: the nearest evenly dividing step, rounded down; a note when
    rounded. Below 60 s cron cannot run it: exit 69, never a silent stretch."""
    if n < 60:
        raise SchedError(EX_UNAVAILABLE, f"cron cannot run every {n}s (its resolution is 1 minute); use systemd")
    mins = n // 60
    if mins < 60:
        step = max(d for d in (1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30) if d <= mins)
        sched, actual = ("* * * * *" if step == 1 else f"*/{step} * * * *"), step * 60
    elif mins < 24 * 60:
        hours = mins // 60
        step = max(d for d in (1, 2, 3, 4, 6, 8, 12) if d <= hours)
        sched, actual = ("0 * * * *" if step == 1 else f"0 */{step} * * *"), step * 3600
    else:
        sched, actual = "0 0 * * *", 86400
    note = None if actual == n else f"StartInterval {n}s rounded down to every {actual}s for cron"
    return sched, note


def _cron_calendar(c: Mapping[str, int]) -> str:
    def f(k: str) -> str:
        return str(c[k] % 7 if k == "Weekday" else c[k]) if k in c else "*"
    return " ".join(f(k) for k in ("Minute", "Hour", "Day", "Month", "Weekday"))


def cron_begin(label: str) -> str:
    return f"# BEGIN ade-sched:{label}"


def cron_end(label: str) -> str:
    return f"# END ade-sched:{label}"


def render_cron(job: Job, home: str | None = None, flock: str | None = "auto") -> tuple[str, list[str]]:
    """The crontab block (BEGIN/END markers included, newline-terminated), notes. KeepAlive and a StartInterval under 60 s
    raise 69. `home` fills ~/.local/bin at the front of PATH (default $HOME). `flock` (default: found on PATH; None: off)
    wraps each run in `flock -n ~/.local/state/ade/LABEL.cron.lock`, so a run that outlasts its interval is not started
    twice (launchd and systemd never overlap a job; cron would)."""
    if job.supervised:
        raise SchedError(EX_UNAVAILABLE, f"{job.label}: KeepAlive needs a supervisor and cron cannot supervise; use systemd or launchd")
    home = home or os.environ.get("HOME") or str(Path.home())
    notes = _common_notes(job, "cron")
    if job.nice is not None or job.low_io or job.process_type:
        notes.append(f"{job.label}: Nice/LowPriorityIO/ProcessType are ignored on cron")
    if job.kill_mode:
        notes.append(f"{job.label}: KillMode is ignored on cron (cron never kills a job's children)")
    scheds: list[str] = []
    if job.interval is not None:
        s, note = _cron_interval(job.interval)
        scheds.append(s)
        if note:
            notes.append(f"{job.label}: {note}")
    scheds += [_cron_calendar(c) for c in job.calendar]
    if job.run_at_load:
        scheds.append("@reboot")
    if not scheds:
        raise SchedError(EX_USAGE, f"{job.source}: no StartInterval, StartCalendarInterval or RunAtLoad: nothing to schedule")
    _clean(home, "HOME")
    prefix = [f"{home}/.local/bin", *PATH_PREFIX]
    env = {"PATH": ":".join(prefix + [p for p in _path_entries(job) if p not in prefix])}
    env.update((k, v) for k, v in job.env.items() if k != "PATH")
    if flock == "auto":
        flock = shutil.which("flock")
    cmd = ""
    if job.cwd:
        cmd += f"cd {shlex.quote(job.cwd)} && "
    if flock:
        _clean(flock, "flock")
        # mkdir -p first: a block pasted by hand (--no-activate, --dry-run) before ~/.local/state/ade exists would
        # otherwise fail every run in flock, silently when the job has no log (adversary C1 on PR 291)
        cmd += f"mkdir -p {shlex.quote(home + '/.local/state/ade')} && "
        cmd += shlex.join([flock, "-n", f"{home}/.local/state/ade/{job.label}.cron.lock"]) + " "
    else:
        notes.append(f"{job.label}: no flock on PATH: a run that outlasts its interval can overlap the next one")
    cmd += "/usr/bin/env " + " ".join(shlex.quote(f"{k}={v}") for k, v in env.items()) + " "
    cmd += shlex.join(job.argv)
    if job.stdout and job.stdout == job.stderr:
        cmd += f" >>{shlex.quote(job.stdout)} 2>&1"
    else:
        cmd += f" >>{shlex.quote(job.stdout)}" if job.stdout else " >/dev/null"
        cmd += f" 2>>{shlex.quote(job.stderr)}" if job.stderr else " 2>/dev/null"
    cmd = cmd.replace("%", "\\%")   # after shlex.quote: cron turns a bare % into a newline
    lines = [cron_begin(job.label), _header(job), *(f"{s} {cmd}" for s in scheds), cron_end(job.label)]
    return "\n".join(lines) + "\n", notes


def render_launchd(job: Job) -> str:
    raw = {k: v for k, v in job.raw.items() if k != "KillMode"}
    text = plistlib.dumps(raw, fmt=plistlib.FMT_XML, sort_keys=False).decode()
    comment = f"<!-- {GENERATED} from {job.source.replace('--', '-')}; edit the plist -->"
    head, sep, rest = text.partition("<plist ")
    return f"{head}{comment}\n{sep}{rest}" if sep else text


# -- environment and backend detection -------------------------------------------------------------------------------

Runner = Callable[[list[str], Mapping[str, str]], tuple[int, str, str]]


def _run(argv: list[str], env: Mapping[str, str], stdin: str | None = None) -> tuple[int, str, str]:
    try:
        p = subprocess.run(argv, env=dict(env), input=stdin, capture_output=True, text=True, timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired) as e:
        return 127, "", str(e)
    return p.returncode, p.stdout, p.stderr


def _abs_env(env: Mapping[str, str], key: str) -> str | None:
    v = env.get(key, "")
    return v if v and os.path.isabs(v) else None   # a relative XDG_* value counts as unset (XDG Base Directory spec)


def _home(env: Mapping[str, str]) -> Path:
    return Path(env.get("HOME") or Path.home())


def tool(name: str, env: Mapping[str, str] | None = None, override: str | None = None,
         which: Callable[..., str | None] = shutil.which) -> str | None:
    """The binary for launchctl/systemctl/loginctl/crontab: per-call override, ADE_SCHED_<NAME>, then PATH."""
    env = os.environ if env is None else env
    if override:
        return override
    if env.get(ENV_BIN[name]):
        return env[ENV_BIN[name]]
    return which(name, path=env.get("PATH"))


def launch_agents_dir(env: Mapping[str, str] | None = None, override: str | os.PathLike[str] | None = None) -> Path:
    env = os.environ if env is None else env
    if override:
        return Path(override)
    return Path(env.get("ADE_SCHED_LAUNCH_AGENTS") or _home(env) / "Library/LaunchAgents")


def unit_dir(env: Mapping[str, str] | None = None, override: str | os.PathLike[str] | None = None) -> Path:
    env = os.environ if env is None else env
    if override:
        return Path(override)
    if env.get("ADE_SCHED_UNIT_DIR"):
        return Path(env["ADE_SCHED_UNIT_DIR"])
    return Path(_abs_env(env, "XDG_CONFIG_HOME") or _home(env) / ".config") / "systemd/user"


def lock_path(env: Mapping[str, str] | None = None, override: str | os.PathLike[str] | None = None) -> Path:
    env = os.environ if env is None else env
    if override:
        return Path(override)
    if env.get("ADE_SCHED_LOCK"):
        return Path(env["ADE_SCHED_LOCK"])
    return Path(_abs_env(env, "XDG_STATE_HOME") or _home(env) / ".local/state") / "ade/ade-sched.lock"


def systemd_env(env: Mapping[str, str], uid: int | None = None, run_user_dir: str = "/run/user",
                exists: Callable[[str], bool] = os.path.exists) -> dict[str, str]:
    """env for `systemctl --user`: when XDG_RUNTIME_DIR is unset (cron, ssh without pam_systemd, sudo -u) and the user's bus
    socket exists, point at it, so the user manager answers."""
    out = dict(env)
    uid = os.getuid() if uid is None else uid
    rt = f"{run_user_dir}/{uid}"
    if not out.get("XDG_RUNTIME_DIR") and exists(f"{rt}/bus"):
        out["XDG_RUNTIME_DIR"] = rt
        out.setdefault("DBUS_SESSION_BUS_ADDRESS", f"unix:path={rt}/bus")
    return out


@dataclass(frozen=True)
class Backend:
    name: str
    env: dict[str, str]        # the environment children get (systemd: XDG_RUNTIME_DIR fixed up)
    reason: str


def detect(backend: str | None = None, env: Mapping[str, str] | None = None, platform: str | None = None,
           which: Callable[..., str | None] = shutil.which, run: Runner | None = None,
           booted_dir: str = "/run/systemd/system", run_user_dir: str = "/run/user", uid: int | None = None,
           exists: Callable[[str], bool] = os.path.exists) -> Backend:
    """Pick the scheduler. Order: explicit `backend`; ADE_SCHED_BACKEND; darwin with launchctl; a booted systemd whose user
    manager answers (read from STDOUT: `degraded` exits 1 and works); a booted systemd whose user manager does not answer is
    exit 69, never a silent cron; crontab on PATH; else 69."""
    env = dict(os.environ if env is None else env)
    platform = sys.platform if platform is None else platform
    run = run or (lambda argv, e: _run(argv, e))
    sd_env = systemd_env(env, uid=uid, run_user_dir=run_user_dir, exists=exists)
    for choice, why in ((backend, "--backend"), (env.get("ADE_SCHED_BACKEND"), "ADE_SCHED_BACKEND")):
        if not choice or choice == "auto":
            continue
        if choice == "none":
            raise SchedError(EX_UNAVAILABLE, f"scheduling is off ({why}=none)")
        if choice not in BACKENDS:
            raise SchedError(EX_USAGE, f"{why} must be auto, launchd, systemd, cron or none, not {choice!r}")
        return Backend(choice, sd_env if choice == "systemd" else env, why)
    if platform == "darwin" and tool("launchctl", env, which=which):
        return Backend("launchd", env, "darwin")
    if os.path.isdir(booted_dir):
        sc = tool("systemctl", env, which=which)
        state = "no systemctl"
        if sc:
            rc, out, err = run([sc, "--user", "is-system-running"], sd_env)
            word = out.strip()
            if word in SYSTEMD_UP:
                return Backend("systemd", sd_env, f"systemd user manager {word}")
            state = word or (err.strip().splitlines() or [f"rc={rc}"])[0]
        uid_ = os.getuid() if uid is None else uid
        raise SchedError(EX_UNAVAILABLE,
                         f"systemd is booted but the user manager is unreachable (systemctl --user is-system-running: "
                         f"{state}). Run from a login session, or export XDG_RUNTIME_DIR={run_user_dir}/{uid_} "
                         f"DBUS_SESSION_BUS_ADDRESS=unix:path={run_user_dir}/{uid_}/bus "
                         f"(sudo loginctl enable-linger $USER keeps the manager up without a session); "
                         f"or pick a backend with --backend / ADE_SCHED_BACKEND")
    if tool("crontab", env, which=which):
        return Backend("cron", env, "crontab on PATH")
    raise SchedError(EX_UNAVAILABLE, "no scheduler: not macOS with launchctl, no running systemd, no crontab on PATH")


# -- install / uninstall / status ------------------------------------------------------------------------------------

@dataclass
class Rendered:
    backend: str
    files: dict[Path, str]                       # path -> content (cron: the block under the pseudo path "crontab")
    notes: list[str]
    activation: list[list[str]]                  # argvs install runs (or prints with activate=False)
    cron_block: str | None = None


@dataclass(frozen=True)
class Status:
    backend: str
    label: str
    installed: bool
    active: bool | None
    next_run: str | None
    paths: tuple[str, ...] = ()


@dataclass
class _Ctx:
    backend: Backend
    agents_dir: Path
    units: Path
    lock: Path
    launchctl: str
    systemctl: str
    loginctl: str
    crontab: str | None
    uid: int
    user: str

    @property
    def env(self) -> dict[str, str]:
        return self.backend.env


OVERRIDES = ("agents_dir", "unit_dir", "lock_path", "launchctl", "systemctl", "loginctl", "crontab")


def _ctx(backend: str | Backend | None, env: Mapping[str, str] | None, overrides: Mapping[str, Any]) -> _Ctx:
    bad = set(overrides) - set(OVERRIDES)
    if bad:
        raise TypeError(f"unknown override(s): {', '.join(sorted(bad))}")
    o = {k: overrides.get(k) for k in OVERRIDES}
    env = dict(os.environ if env is None else env)
    b = backend if isinstance(backend, Backend) else detect(backend, env)
    uid = os.getuid()
    try:
        user = env.get("USER") or pwd.getpwuid(uid).pw_name
    except KeyError:
        user = str(uid)
    return _Ctx(backend=b, agents_dir=launch_agents_dir(env, o["agents_dir"]), units=unit_dir(env, o["unit_dir"]),
                lock=lock_path(env, o["lock_path"]), launchctl=tool("launchctl", env, o["launchctl"]) or "launchctl",
                systemctl=tool("systemctl", env, o["systemctl"]) or "systemctl",
                loginctl=tool("loginctl", env, o["loginctl"]) or "loginctl", crontab=tool("crontab", env, o["crontab"]),
                uid=uid, user=user)


def atomic_write(path: Path, text: str, mode: int = 0o600) -> None:
    """Temp file beside, then os.replace; 0600 (a unit or plist can name state paths; nobody else needs to read it)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _sd_version(c: _Ctx) -> int | None:
    rc, out, _ = _run([c.systemctl, "--version"], c.env)
    m = re.match(r"systemd (\d+)", out.strip())
    return int(m.group(1)) if rc == 0 and m else None


def systemd_version(env: Mapping[str, str] | None = None, **overrides: Any) -> int | None:
    """`systemctl --version`'s number, None when unknown (then append: is assumed)."""
    return _sd_version(_ctx("systemd", env, overrides))


def _render(job: Job, c: _Ctx) -> Rendered:
    name = c.backend.name
    if name == "launchd":
        path = c.agents_dir / f"{job.label}.plist"
        return Rendered(name, {path: render_launchd(job)}, [],
                        [[c.launchctl, "bootout", f"gui/{c.uid}/{job.label}"],
                         [c.launchctl, "bootstrap", f"gui/{c.uid}", str(path)]])
    if name == "systemd":
        files, notes = render_systemd(job, _sd_version(c))
        unit = f"{job.label}.timer" if f"{job.label}.timer" in files else f"{job.label}.service"
        restart = [c.systemctl, "--user", "restart", unit] if unit.endswith(".timer") else \
            [c.systemctl, "--user", "restart", "--no-block", unit]
        return Rendered(name, {c.units / f: t for f, t in files.items()}, notes,
                        [[c.systemctl, "--user", "daemon-reload"], [c.systemctl, "--user", "enable", unit], restart])
    block, notes = render_cron(job, home=str(_home(c.env)))
    return Rendered(name, {Path("crontab"): block}, notes, [[c.crontab or "crontab", "-"]], cron_block=block)


def render(job: Job, backend: str | Backend, env: Mapping[str, str] | None = None, **overrides: Any) -> Rendered:
    """What install would write and run, without touching anything."""
    return _render(job, _ctx(backend, env, overrides))


def print_artifacts(r: Rendered, out: TextIO) -> None:
    for path, text in r.files.items():
        print(f"# {'crontab (user)' if r.cron_block is not None else path}", file=out)
        out.write(text if text.endswith("\n") else text + "\n")


def _activate(c: _Ctx, argv: list[str], ignore: bool = False, stdin: str | None = None) -> tuple[int, str, str]:
    rc, out, err = _run(argv, c.env, stdin)
    if rc != 0 and not ignore:
        raise SchedError(EX_ACTIVATE, f"{shlex.join(argv)} failed (rc={rc}): {(err or out).strip()}")
    return rc, out, err


class _CronLock:
    def __init__(self, path: Path):
        self.path = path

    def __enter__(self) -> "_CronLock":
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fh = open(self.path, "a")   # held for the with block
        fcntl.flock(self.fh, fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc: object) -> None:
        fcntl.flock(self.fh, fcntl.LOCK_UN)
        self.fh.close()


def _crontab_read(c: _Ctx) -> str:
    """The current crontab. Only rc 1 with "no crontab" on stderr means empty; any other failure raises 1, so the caller
    never writes a crontab built from a bad read (that would wipe the operator's crontab)."""
    if not c.crontab:
        raise SchedError(EX_UNAVAILABLE, "no crontab binary")
    rc, out, err = _run([c.crontab, "-l"], c.env)
    if rc == 0:
        return out
    if rc == 1 and "no crontab" in err.lower():
        return ""
    raise SchedError(EX_ACTIVATE, f"{c.crontab} -l failed (rc={rc}): {(err or out).strip()}; the crontab was not changed")


def drop_cron_block(text: str, label: str) -> tuple[str, bool]:
    """text without the label's ade-sched block (every copy), and whether one was there. Foreign lines are kept."""
    begin, end = cron_begin(label), cron_end(label)
    kept: list[str] = []
    inside = found = False
    for line in text.splitlines(keepends=True):
        s = line.rstrip("\n")
        if not inside and s == begin:
            inside = found = True
            continue
        if inside:
            if s == end:
                inside = False
            continue
        kept.append(line)
    if inside:      # a BEGIN without its END: dropping "the rest" would delete the operator's own lines
        raise SchedError(EX_ACTIVATE, f"crontab has '{begin}' with no '{end}' (a hand-edited block?); "
                                      f"fix it with crontab -e; the crontab was not changed")
    out = "".join(kept)
    if out and not out.endswith("\n"):
        out += "\n"
    return out, found


def _cron_remove(c: _Ctx, label: str, err: TextIO, quiet_missing: bool = False) -> bool:
    if not c.crontab:
        return False
    with _CronLock(c.lock):
        try:
            cur = _crontab_read(c)
        except SchedError:
            if quiet_missing:
                return False
            raise
        new, found = drop_cron_block(cur, label)
        if found:
            _activate(c, [c.crontab, "-"], stdin=new)
            print(f"ade-sched: removed the crontab block for {label}", file=err)
        return found


def _linger(c: _Ctx) -> str | None:
    rc, out, _ = _run([c.loginctl, "show-user", c.user, "-p", "Linger", "--value"], c.env)
    v = out.strip()
    return v if rc == 0 and v in ("yes", "no") else None


def linger(env: Mapping[str, str] | None = None, **overrides: Any) -> str | None:
    """loginctl's Linger for this user: "yes", "no" or None when unknown."""
    return _linger(_ctx("systemd", env, overrides))


def _linger_msg(c: _Ctx, label: str) -> str:
    return (f"linger is off for {c.user}: user timers stop at logout, so {label} would run only while {c.user} has a "
            f"session; for boot-time runs: sudo loginctl enable-linger {c.user}")


def _log_dirs(job: Job) -> None:
    for p in (job.stdout, job.stderr):
        if p:
            Path(p).parent.mkdir(parents=True, exist_ok=True)


def install(job: Job, backend: str | Backend | None = None, *, dry_run: bool = False, activate: bool = True,
            allow_no_linger: bool = False, env: Mapping[str, str] | None = None, out: TextIO | None = None,
            err: TextIO | None = None, **overrides: Any) -> Rendered:
    """Install `job` on the backend (auto-detected when None). dry_run prints every artifact under a `# <path>` header and
    the commands, changing nothing; activate=False writes the files and prints the activation commands instead of running
    them. On systemd, Linger=no is exit 69 before anything is written unless allow_no_linger. Raises SchedError."""
    out = out or sys.stdout
    err = err or sys.stderr
    c = _ctx(backend, env, overrides)
    r = _render(job, c)
    for n in r.notes:
        print(f"ade-sched: note: {n}", file=err)
    if dry_run:
        print_artifacts(r, out)
        if r.backend == "cron":
            print("# then: crontab -l, drop the old block, append this one, crontab -", file=out)
        else:
            for argv in r.activation:
                print(f"# run: {shlex.join(argv)}", file=out)
        return r
    if job.worktree:
        raise SchedError(EX_USAGE, f"__ADE__ defaulted to {job.worktree}, a linked git worktree that is deleted after its "
                                   f"merge; install from the primary checkout (or pass --ade DIR where the tool has it)")
    if r.backend == "systemd":
        state = _linger(c)
        if state == "no" and not allow_no_linger:
            raise SchedError(EX_UNAVAILABLE, _linger_msg(c, job.label) + " (or --allow-no-linger to install anyway)")
        if state == "no":
            print(f"ade-sched: {_linger_msg(c, job.label)}", file=err)
        elif state is None:
            print(f"ade-sched: note: could not read Linger for {c.user} ({c.loginctl} show-user)", file=err)
    if r.backend == "cron":
        if not activate:
            print("# add this block with `crontab -e` (ade-sched install --backend cron does it for you):", file=out)
            print_artifacts(r, out)
            return r
        if not c.crontab:
            raise SchedError(EX_UNAVAILABLE, "no crontab binary")
        _log_dirs(job)
        (_home(c.env) / ".local/state/ade").mkdir(parents=True, exist_ok=True)   # where each run's flock -n lock lives
        with _CronLock(c.lock):
            cur, _ = drop_cron_block(_crontab_read(c), job.label)
            _activate(c, [c.crontab, "-"], stdin=cur + (r.cron_block or ""))
        return r
    _log_dirs(job)
    if r.backend == "systemd":
        stale = c.units / f"{job.label}.timer"
        if stale not in r.files and stale.exists():   # the job lost its schedule: the old timer would keep firing
            if activate:
                _activate(c, [c.systemctl, "--user", "disable", "--now", stale.name], ignore=True)
            stale.unlink()
    for path, text in r.files.items():
        atomic_write(path, text)
    if not activate:
        for argv in r.activation:
            print(shlex.join(argv), file=out)
        return r
    for i, argv in enumerate(r.activation):
        _activate(c, argv, ignore=(r.backend == "launchd" and i == 0))   # bootout of a job not loaded fails: fine
    if r.backend == "systemd":
        _cron_remove(c, job.label, err, quiet_missing=True)
    return r


def uninstall(label: str, backend: str | Backend | None = None, *, dry_run: bool = False, activate: bool = True,
              env: Mapping[str, str] | None = None, out: TextIO | None = None, err: TextIO | None = None,
              **overrides: Any) -> bool:
    """Remove the job; True when something was installed. Not installed is not an error."""
    out = out or sys.stdout
    err = err or sys.stderr
    if not LABEL_RE.fullmatch(label):
        raise SchedError(EX_USAGE, f"bad label {label!r}")
    c = _ctx(backend, env, overrides)
    name = c.backend.name
    if name == "launchd":
        path = c.agents_dir / f"{label}.plist"
        cmd = [c.launchctl, "bootout", f"gui/{c.uid}/{label}"]
        if dry_run:
            print(f"# remove {path}" if path.exists() else f"# {path} not present", file=out)
            print(f"# run: {shlex.join(cmd)}", file=out)
            return path.exists()
        if activate:
            _activate(c, cmd, ignore=True)
        else:
            print(shlex.join(cmd), file=out)
        found = path.exists()
        path.unlink(missing_ok=True)
        return found
    if name == "systemd":
        present = [u for u in (c.units / f"{label}.timer", c.units / f"{label}.service") if u.exists()]
        cmds = [[c.systemctl, "--user", "disable", "--now", u.name] for u in present]
        reload_ = [c.systemctl, "--user", "daemon-reload"]
        if dry_run:
            for u in present:
                print(f"# remove {u}", file=out)
            for argv in cmds + ([reload_] if present else []):
                print(f"# run: {shlex.join(argv)}", file=out)
            return bool(present)
        if not activate:
            for argv in cmds + ([reload_] if present else []):
                print(shlex.join(argv), file=out)
            for u in present:
                u.unlink()
            return bool(present)
        for argv in cmds:
            _activate(c, argv, ignore=True)   # a unit that is not loaded fails to disable: fine
        for u in present:
            u.unlink()
        if present:
            _activate(c, reload_)
        _cron_remove(c, label, err, quiet_missing=True)
        return bool(present)
    if dry_run:
        print(f"# remove the crontab block ade-sched:{label} if present", file=out)
        return False
    if not activate:
        print(f"# remove the lines from {cron_begin(label)} to {cron_end(label)} with `crontab -e`", file=out)
        return False
    return _cron_remove(c, label, err)


def status(label: str, backend: str | Backend | None = None, *, env: Mapping[str, str] | None = None,
           **overrides: Any) -> Status:
    """Best effort: installed (the files or block exist), active (loaded / timer active), next_run (systemd: the timer's
    next elapse; cron: the schedule; launchd: None)."""
    c = _ctx(backend, env, overrides)
    name = c.backend.name
    if name == "launchd":
        path = c.agents_dir / f"{label}.plist"
        installed = path.exists()
        rc, _, _ = _run([c.launchctl, "print", f"gui/{c.uid}/{label}"], c.env)
        return Status(name, label, installed, rc == 0, None, (str(path),) if installed else ())
    if name == "systemd":
        timer, svc = c.units / f"{label}.timer", c.units / f"{label}.service"
        installed = svc.exists()
        unit = timer if timer.exists() else svc
        active = False
        if installed:
            _, o, _ = _run([c.systemctl, "--user", "is-active", unit.name], c.env)
            active = o.strip() in ("active", "activating", "reloading")
        nxt = None
        if timer.exists():
            rc, o, _ = _run([c.systemctl, "--user", "show", timer.name, "-p", "NextElapseUSecRealtime", "--value"], c.env)
            nxt = (o.strip() or None) if rc == 0 else None
        return Status(name, label, installed, active, nxt, tuple(str(p) for p in (svc, timer) if p.exists()))
    try:
        text = _crontab_read(c)
    except SchedError:
        return Status(name, label, False, None, None)
    begin, end = cron_begin(label), cron_end(label)
    lines = text.splitlines()
    if begin not in lines:
        return Status(name, label, False, False, None)
    block = lines[lines.index(begin) + 1:]
    block = block[:block.index(end)] if end in block else block
    scheds = ["@reboot" if ln.startswith("@reboot") else " ".join(ln.split()[:5])
              for ln in block if ln.strip() and not ln.startswith("#")]
    return Status(name, label, True, True, "; ".join(scheds) or None, ("crontab",))


def installed_labels(backend: str | Backend | None = None, *, env: Mapping[str, str] | None = None,
                     **overrides: Any) -> list[str]:
    """Labels of the jobs ade-sched generated on this backend (launchd and systemd: files carrying the generated comment)."""
    c = _ctx(backend, env, overrides)
    name = c.backend.name
    found: set[str] = set()
    if name == "cron":
        try:
            text = _crontab_read(c)
        except SchedError:
            return []
        return sorted({ln[len("# BEGIN ade-sched:"):].strip() for ln in text.splitlines()
                       if ln.startswith("# BEGIN ade-sched:")})
    d, ext = (c.agents_dir, ".plist") if name == "launchd" else (c.units, ".service")
    if d.is_dir():
        for p in d.glob(f"*{ext}"):
            try:
                head = p.read_text(errors="replace")[:4096]
            except OSError:
                continue
            if GENERATED in head:
                found.add(p.name[: -len(ext)])
    return sorted(found)


@dataclass(frozen=True)
class LiveJob:
    """One loaded/on-disk schedule identity discovered on the machine."""

    id: str
    backend: str  # launchd | systemd | cron | paseo
    source: str  # generated | file | crontab | paseo
    active: bool | None = None


@dataclass(frozen=True)
class LiveScan:
    backend: str
    jobs: tuple[LiveJob, ...]
    notes: tuple[str, ...] = ()

    @property
    def ids(self) -> set[str]:
        return {j.id for j in self.jobs}


@dataclass(frozen=True)
class DriftRow:
    """One inventory vs live comparison row. action is always report (never unload)."""

    name: str
    status: str
    owner: str
    detail: str
    category: str = "job"  # job | retired | foreign
    fail: bool = False
    action: str = "report"


def _label_matches(pattern: str, label: str) -> bool:
    if any(ch in pattern for ch in "*?["):
        return fnmatch.fnmatchcase(label, pattern)
    return pattern == label


def _foreign_candidate(label: str) -> bool:
    return any(label.startswith(p) for p in FOREIGN_PREFIXES)


def list_backend_labels(backend: str | Backend | None = None, *, env: Mapping[str, str] | None = None,
                        **overrides: Any) -> list[LiveJob]:
    """All on-disk labels for the active backend (ade-sched generated and sibling unit/plist files)."""
    c = _ctx(backend, env, overrides)
    name = c.backend.name
    out: list[LiveJob] = []
    if name == "cron":
        try:
            text = _crontab_read(c)
        except SchedError as e:
            raise SchedError(e.code, f"crontab read for scan: {e}") from e
        for ln in text.splitlines():
            if ln.startswith("# BEGIN ade-sched:"):
                label = ln[len("# BEGIN ade-sched:"):].strip()
                if label:
                    out.append(LiveJob(label, "cron", "crontab", True))
        return out
    if name == "launchd":
        d = c.agents_dir
        if d.is_dir():
            for p in sorted(d.glob("*.plist")):
                try:
                    head = p.read_text(errors="replace")[:4096]
                except OSError:
                    continue
                src = "generated" if GENERATED in head else "file"
                st = status(p.stem, c.backend, env=c.env, agents_dir=c.agents_dir, launchctl=c.launchctl)
                out.append(LiveJob(p.stem, "launchd", src, st.active if st.installed else False))
        return out
    # systemd
    d = c.units
    if d.is_dir():
        for p in sorted(d.glob("*.service")):
            try:
                head = p.read_text(errors="replace")[:4096]
            except OSError:
                continue
            src = "generated" if GENERATED in head else "file"
            st = status(p.stem, c.backend, env=c.env, unit_dir=c.units, systemctl=c.systemctl)
            out.append(LiveJob(p.stem, "systemd", src, st.active if st.installed else False))
    return out


def paseo_schedule_names(
    *,
    run: Callable[[list[str]], subprocess.CompletedProcess[str]] | None = None,
    which: Callable[[str], str | None] = shutil.which,
) -> tuple[list[LiveJob], tuple[str, ...]]:
    """Names from `paseo schedule ls --json`. Missing/unavailable paseo is a note, not an error."""
    notes: list[str] = []
    if run is None:
        if which("paseo") is None:
            return [], ("paseo not on PATH; paseo schedules not probed",)

        def run(argv: list[str]) -> subprocess.CompletedProcess[str]:
            return subprocess.run(  # noqa: S603 — argv list only
                argv, capture_output=True, text=True, check=False, timeout=30,
            )

    try:
        proc = run(["paseo", "schedule", "ls", "--json"])
    except subprocess.TimeoutExpired:
        notes.append("paseo schedule ls failed (timeout)")
        return [], tuple(notes)
    except OSError as e:
        # FileNotFoundError and other launch failures: treat as unavailable, never traceback.
        notes.append(f"paseo schedule ls failed (launch: {e})")
        return [], tuple(notes)
    if proc.returncode != 0:
        notes.append(f"paseo schedule ls failed (rc={proc.returncode})")
        return [], tuple(notes)
    text = (proc.stdout or "").strip()
    if not text:
        return [], tuple(notes)
    try:
        data = json.loads(text)
    except ValueError:
        notes.append("paseo schedule ls: invalid JSON")
        return [], tuple(notes)
    rows = data if isinstance(data, list) else data.get("schedules") or data.get("items") or []
    if not isinstance(rows, list):
        notes.append("paseo schedule ls: unexpected JSON shape")
        return [], tuple(notes)
    out: list[LiveJob] = []
    for row in rows:
        if isinstance(row, str):
            out.append(LiveJob(row, "paseo", "paseo", True))
            continue
        if not isinstance(row, dict):
            continue
        name = row.get("name") or row.get("Name") or row.get("id") or row.get("Id")
        if isinstance(name, str) and name:
            out.append(LiveJob(name, "paseo", "paseo", True))
    return out, tuple(notes)


def scan_live(
    backend: str | Backend | None = None,
    *,
    env: Mapping[str, str] | None = None,
    paseo_run: Callable[[list[str]], subprocess.CompletedProcess[str]] | None = None,
    skip_paseo: bool = False,
    **overrides: Any,
) -> LiveScan:
    """Discover live schedule identities on launchd/systemd/cron plus paseo schedules."""
    notes: list[str] = []
    try:
        b = detect(backend, env=env) if not isinstance(backend, Backend) else backend
    except SchedError as e:
        notes.append(f"backend detect: {e}")
        backend_jobs: list[LiveJob] = []
        bname = "none"
    else:
        bname = b.name
        try:
            backend_jobs = list_backend_labels(b, env=env, **overrides)
        except SchedError as e:
            notes.append(f"backend scan: {e}")
            backend_jobs = []
    paseo_jobs: list[LiveJob] = []
    if not skip_paseo:
        paseo_jobs, pnotes = paseo_schedule_names(run=paseo_run)
        notes.extend(pnotes)
    return LiveScan(bname, tuple(backend_jobs + paseo_jobs), tuple(notes))


def _job_expected(row: dict[str, Any]) -> bool:
    cls = row.get("class")
    if cls == "hard":
        return True
    if cls in ("offered", "optional"):
        return bool(row.get("chosen"))
    return False


def diff_jobs(
    jobs: list[dict[str, Any]],
    retired: list[dict[str, Any]],
    live: LiveScan | Mapping[str, Any] | set[str] | None,
    *,
    unload: bool = False,
) -> list[DriftRow]:
    """Compare inventory to live state. Never unloads (unload=True is refused as report-only).

    ADE-owned expected jobs: missing/present → fail doctor when probeable.
    Retired labels that are still live → fail (report only; removal is a later update step).
    Foreign / unknown owners → report, never unload.
    """
    if unload:
        # Explicit refuse: S4b inventory slice and standing rule never unload foreign (or any) owners here.
        unload = False
    if live is None:
        ids: set[str] = set()
        notes: tuple[str, ...] = ()
        live_jobs: tuple[LiveJob, ...] = ()
        backend_name = "none"
    elif isinstance(live, LiveScan):
        ids = live.ids
        notes = live.notes
        live_jobs = live.jobs
        backend_name = live.backend
    elif isinstance(live, set):
        ids = set(live)
        notes = ()
        live_jobs = tuple(LiveJob(i, "unknown", "set", None) for i in sorted(ids))
        backend_name = "set"
    else:
        # Mapping with optional "ids" / "jobs"
        raw_ids = live.get("ids") if isinstance(live.get("ids"), (set, list, tuple)) else None
        ids = set(raw_ids) if raw_ids is not None else set()
        notes = tuple(live.get("notes") or ())
        live_jobs = tuple(live.get("jobs") or ())
        backend_name = str(live.get("backend") or "unknown")

    # When no host scheduler is reachable — or detection succeeded but enumeration failed —
    # ade-sched jobs are unprobeable (unknown), not missing. A failed scan keeps the backend
    # name in notes ("backend scan: …") so we do not treat an unreadable scheduler as empty.
    sched_probeable = (
        backend_name in BACKENDS
        and not any(n.startswith("backend scan:") for n in notes)
    )
    paseo_probeable = not any(
        "paseo not on PATH" in n or "paseo schedule ls failed" in n for n in notes
    )

    inventory_labels: set[str] = set()
    rows: list[DriftRow] = []
    for n in notes:
        rows.append(DriftRow("live-scan", "unknown", OWNER_ADE, n, category="job", fail=False))

    for row in jobs:
        name = str(row["name"])
        owner = str(row.get("owner") or "?")
        kind = str(row.get("kind") or "")
        label = row.get("label")
        if isinstance(label, str) and label:
            inventory_labels.add(label)
        if not _job_expected(row):
            rows.append(DriftRow(
                name, "unchosen", owner,
                f"{kind} not chosen; doctor quiet",
                fail=False,
            ))
            continue
        if kind == "service":
            # Dependency/site services: inventory + report only in this slice (never unload / never repair).
            lab = label if isinstance(label, str) else "-"
            rows.append(DriftRow(
                name, "unknown", owner,
                f"service owner={owner} label={lab}; observe-only (never unload; live probe later)",
                fail=False,
            ))
            continue
        if kind == "paseo":
            assert isinstance(label, str)
            if not paseo_probeable:
                rows.append(DriftRow(
                    name, "unknown", owner,
                    f"paseo schedule {label!r} not probed (paseo unavailable)",
                    fail=False,
                ))
            elif label in ids:
                rows.append(DriftRow(
                    name, "ok", owner,
                    f"paseo schedule {label!r} present (mode={row.get('mode')})",
                    fail=False,
                ))
            else:
                rows.append(DriftRow(
                    name, "missing", owner,
                    f"paseo schedule {label!r} absent; mode must stay explicit on create",
                    fail=owner == OWNER_ADE,
                ))
            continue
        # ade-sched
        if not isinstance(label, str) or not label:
            rows.append(DriftRow(
                name, "planned", owner,
                row.get("notes") or "no label/plist yet; inventory only",
                fail=False,
            ))
            continue
        if not sched_probeable:
            why = (
                "backend enumeration failed"
                if any(n.startswith("backend scan:") for n in notes)
                else f"no host scheduler; backend={backend_name}"
            )
            rows.append(DriftRow(
                name, "unknown", owner,
                f"label {label} not probed ({why})",
                fail=False,
            ))
        elif label in ids:
            rows.append(DriftRow(
                name, "ok", owner,
                f"label {label} present on live scan",
                fail=False,
            ))
        else:
            rows.append(DriftRow(
                name, "missing", owner,
                f"label {label} absent (plist={row.get('plist') or '-'})",
                fail=owner == OWNER_ADE,
            ))

    for row in retired:
        name = str(row["name"])
        owner = str(row.get("owner") or "?")
        pattern = str(row.get("label") or "")
        inventory_labels.add(pattern)
        if not sched_probeable:
            why = (
                "backend enumeration failed"
                if any(n.startswith("backend scan:") for n in notes)
                else f"no host scheduler; backend={backend_name}"
            )
            rows.append(DriftRow(
                name, "unknown", owner,
                f"retired label {pattern} not probed ({why})",
                category="retired",
                fail=False,
            ))
            continue
        hits = sorted(i for i in ids if _label_matches(pattern, i))
        if hits:
            rows.append(DriftRow(
                name, "present", owner,
                f"retired label still live: {', '.join(hits)} (report only; never unload here)",
                category="retired",
                fail=True,
            ))
        else:
            rows.append(DriftRow(
                name, "ok", owner,
                f"retired label {pattern} absent",
                category="retired",
                fail=False,
            ))

    known_exact = {lab for lab in inventory_labels if not any(ch in lab for ch in "*?[")}
    for lj in live_jobs:
        if lj.id in known_exact:
            continue
        if any(_label_matches(pat, lj.id) for pat in inventory_labels):
            continue
        if not _foreign_candidate(lj.id) and lj.source != "generated":
            continue
        rows.append(DriftRow(
            lj.id, "foreign", "unknown",
            f"live {lj.backend}/{lj.source} label not in install.jobs (report only; never unload)",
            category="foreign",
            fail=False,
        ))
    return rows


def format_job_list(jobs: list[dict[str, Any]], retired: list[dict[str, Any]]) -> list[str]:
    """Human lines for `ade-sched list`."""
    lines: list[str] = []
    for row in jobs:
        label = row.get("label") or "-"
        plist = row.get("plist") or "-"
        mode = f" mode={row['mode']}" if row.get("mode") else ""
        chosen = ""
        if row.get("class") in ("offered", "optional"):
            chosen = f" chosen={row.get('chosen')}"
        lines.append(
            f"{row['name']}\t{row['kind']}\t{row['owner']}\t{row['class']}{chosen}\t"
            f"label={label}\tplist={plist}{mode}"
        )
    for row in retired:
        lines.append(
            f"retired:{row['name']}\t{row['kind']}\t{row['owner']}\tlabel={row.get('label')}"
        )
    return lines


