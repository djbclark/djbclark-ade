class _ReconcileLock:
    """Exclusive flock beside the ledger for the whole reconcile transaction."""

    def __init__(self, path: Path):
        self.path = path
        self._fh: Any = None

    def __enter__(self) -> "_ReconcileLock":
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._fh = open(self.path, "a+", encoding="utf-8")
        fcntl.flock(self._fh.fileno(), fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc: object) -> None:
        if self._fh is not None:
            try:
                fcntl.flock(self._fh.fileno(), fcntl.LOCK_UN)
            finally:
                self._fh.close()
                self._fh = None


def expand_job_set_item(
    item: str,
    *,
    root: Path,
    env: Mapping[str, str] | None = None,
    prefix: Path | None = None,
) -> tuple[str, str]:
    """Expand ``KEY=VALUE`` catalog set rows; ``{home}/{root}/{bin}/{prefix}`` only."""
    env = os.environ if env is None else env
    key, sep, val = item.partition("=")
    if not sep or not key:
        raise SchedError(EX_USAGE, f"job set wants KEY=VALUE, not {item!r}")
    home = Path(_abs_env(env, "HOME") or Path.home())
    prefix = prefix or (home / ".local" / "bin")
    mapping = {
        "{home}": str(home),
        "{root}": str(root.resolve()),
        "{bin}": str((root / "bin").resolve()),
        "{prefix}": str(Path(prefix).expanduser().resolve()),
    }
    expanded = val
    for token, value in mapping.items():
        expanded = expanded.replace(token, value)
    if "{" in expanded or "}" in expanded:
        raise SchedError(EX_USAGE, f"job set {item!r} still contains braces after known tokens")
    return key, expanded


def job_subst_from_row(
    row: Mapping[str, Any],
    *,
    root: Path,
    env: Mapping[str, str] | None = None,
    extra: Mapping[str, str] | None = None,
) -> dict[str, str]:
    subst: dict[str, str] = dict(extra or {})
    for item in row.get("set") or []:
        if not isinstance(item, str):
            raise SchedError(EX_USAGE, f"job {row.get('name')!r}: set item must be a string")
        key, val = expand_job_set_item(item, root=root, env=env)
        subst[key] = val
    canon = str(admission_dir(None, env=env))   # the wrapper's lock directory: fixed, never a row `set` or `extra_subst` knob
    if subst.get("__ADMISSION__", canon) != canon:
        raise SchedError(EX_USAGE, f"job {row.get('name')!r}: __ADMISSION__ is fixed to {canon} and cannot be set")
    subst["__ADMISSION__"] = canon
    return subst


def _platform_ok(row: Mapping[str, Any], *, platform_name: str | None = None) -> bool:
    platforms = row.get("platforms")
    if not isinstance(platforms, list) or not platforms:
        return True
    sysname = (platform_name or sys.platform).lower()
    aliases = {"linux": ("linux",), "darwin": ("darwin", "mac", "macos"), "mac": ("darwin", "mac", "macos")}
    wanted: set[str] = set()
    for p in platforms:
        if not isinstance(p, str):
            continue
        wanted.update(aliases.get(p.lower(), (p.lower(),)))
    if sysname.startswith("linux"):
        return bool(wanted & set(aliases["linux"]))
    if sysname == "darwin":
        return bool(wanted & set(aliases["darwin"]))
    return True


def artifact_hash(files: Mapping[Path, str]) -> str:
    h = hashlib.sha256()
    for path in sorted(files, key=lambda p: str(p)):
        h.update(str(path.name).encode())
        h.update(b"\0")
        h.update(files[path].encode())
        h.update(b"\0")
    return h.hexdigest()


def extract_cron_block(text: str, label: str) -> str | None:
    """Return the ade-sched crontab block for ``label`` (BEGIN..END inclusive), or None."""
    begin, end = cron_begin(label), cron_end(label)
    lines = text.splitlines(keepends=True)
    start = None
    for i, line in enumerate(lines):
        if line.rstrip("\n") == begin:
            start = i
            break
    if start is None:
        return None
    for j in range(start + 1, len(lines)):
        if lines[j].rstrip("\n") == end:
            block = "".join(lines[start : j + 1])
            if not block.endswith("\n"):
                block += "\n"
            return block
    return None


def _on_disk_files_match(
    rendered: Rendered,
    *,
    backend_name: str,
    label: str,
    env: Mapping[str, str],
    overrides: Mapping[str, Any],
) -> bool:
    """True when installed artifacts match the ADE render (systemd unit files or cron block)."""
    try:
        if backend_name == "cron":
            want = rendered.files.get(Path("crontab"))
            if want is None and rendered.cron_block:
                want = rendered.cron_block
            if want is None:
                return False
            c = _ctx(backend_name, env, dict(overrides))
            text = _crontab_read(c)
            have = extract_cron_block(text, label)
            if have is None:
                return False
            return artifact_hash({Path("crontab"): have}) == artifact_hash({Path("crontab"): want})
        current: dict[Path, str] = {}
        for path in rendered.files:
            if path.is_file():
                current[path] = read_regular_bytes(path).decode("utf-8")
        return set(current) == set(rendered.files) and artifact_hash(current) == artifact_hash(rendered.files)
    except (OSError, SchedError, ValueError):  # ValueError: a non-UTF-8 file is not a match
        return False


def _ledger_owns(entry: Mapping[str, Any] | None, *, label: str) -> bool:
    """Removal authority: only a readable ADE ledger row for this label (intent alone is not enough)."""
    if not isinstance(entry, dict):
        return False
    if entry.get("owner") != OWNER_ADE:
        return False
    if entry.get("label") != label:
        return False
    status = entry.get("status")
    # pending-install is not removal authority; committed / pending-remove are.
    return status in ("committed", "pending-remove", "installed")


def _expects_timer(rendered: Rendered) -> bool:
    """True when the ADE render includes a systemd timer unit (interval/calendar jobs)."""
    return any(isinstance(p, Path) and p.name.endswith(".timer") for p in rendered.files)


def _unit_active_ok(
    st: Status,
    *,
    expects_timer: bool,
    backend_name: str | None = None,
) -> bool:
    """Matching artifacts are healthy only when the manager has them loaded when required.

    Systemd: require active when a ``.timer`` is expected; oneshots without a timer may
    stay inactive. Launchd: always require ``launchctl print`` success (loaded), even
    though plists never produce a ``.timer`` (Codex P2 on #514).
    """
    if backend_name == "launchd":
        return bool(st.active)
    if expects_timer:
        return bool(st.active)
    return True


def _prior_identity(entry: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """Old ledger identity kept until its removal completes (label rename of the same logical name)."""
    if not isinstance(entry, dict):
        return None
    prior = entry.get("prior_identity")
    return prior if isinstance(prior, dict) else None


def _removal_entry(
    entries: Mapping[str, Any],
    name: str,
    label: str,
    *,
    snapshot: Mapping[str, Any] | None = None,
) -> dict[str, Any] | None:
    """Find removal authority for ``label`` under ``name``, including a preserved prior identity."""
    live = entries.get(name)
    if isinstance(live, dict) and live.get("label") == label and _ledger_owns(live, label=label):
        return live
    prior = _prior_identity(live if isinstance(live, dict) else None)
    if prior is not None and prior.get("label") == label and _ledger_owns(prior, label=label):
        return prior
    if isinstance(snapshot, dict) and snapshot.get("label") == label and _ledger_owns(snapshot, label=label):
        return dict(snapshot)
    return None


def _with_prior_identity(
    new_entry: dict[str, Any],
    prev: Mapping[str, Any] | None,
    *,
    new_label: str,
) -> dict[str, Any]:
    """Keep the old owned identity when the logical name's label changes before removal finishes."""
    if not isinstance(prev, dict):
        return new_entry
    old_label = prev.get("label")
    if not isinstance(old_label, str) or not old_label or old_label == new_label:
        return new_entry
    if not _ledger_owns(prev, label=old_label):
        return new_entry
    keep = {
        k: prev[k]
        for k in (
            "logical_id", "label", "owner", "backend", "scope", "paths",
            "artifact_hash", "status", "generation", "detail", "updated_at",
        )
        if k in prev
    }
    # Nested prior from an earlier rename: keep the outermost old label for this transition.
    nested = _prior_identity(prev)
    if nested is not None and nested.get("label") not in (None, old_label, new_label):
        keep = dict(nested)
    return {**new_entry, "prior_identity": keep}


@dataclass(frozen=True)
class JobAdmission:
    """Evidence held by an admission context across the entire mutation.

    An adapter must exclude new launches, observe this job's running work,
    and stop future triggers without killing work. The launchd adapter (`launchd_admission`) does that for a loaded
    job only when its installed plist routes every launch through `bin/ade-job-run` (the per-label admission lock);
    otherwise it admits only jobs that are not loaded, and every other backend keeps the conservative default.
    """

    all_launch_paths: bool = False
    activity: str = "unknown"  # idle | busy | unknown
    triggers_drained: bool = False
    updater_running: bool = False
    hold: str | None = None  # adapter-supplied refusal reason (loaded job, state unreadable, foreign plist, ...)
    locked: bool = False  # the label's EXCLUSIVE admission lock is held until the context exits (wrapper-routed job)
    loaded: bool = False  # ... and the job is loaded, so a locked reload/removal unloads it first

    def refusal(self) -> str | None:
        if self.updater_running:
            return "updater's own running service; next generation pending"
        if self.hold:
            return self.hold
        if not self.all_launch_paths:
            return "shared admission incomplete; launch paths do not all participate"
        if self.activity != "idle":
            return f"per-job activity {self.activity}; preserve running work"
        if not self.triggers_drained:
            return "future triggers cannot be drained safely"
        return None


@dataclass(frozen=True)
class ReconcileStep:
    """One planned reconcile action. touch=True means --yes would mutate host + ledger."""

    name: str
    action: str
    owner: str
    detail: str
    label: str | None = None
    touch: bool = False
    category: str = "job"  # job | retired | foreign | ledger
    ledger_snapshot: Mapping[str, Any] | None = None  # remove: ownership at plan time


# launchctl exit status for "Could not find service" (the label is not loaded).
LAUNCHD_NOT_LOADED_RC = 113
# Jobs that are the updater's own service: busy means the updater is running this reconcile.
UPDATER_LABELS = frozenset({"com.djbclark.ade-update-check"})
_PRINT_FIELD_RE = re.compile(r"\t(state|pid) = (.*)")


def parse_launchd_activity(text: str) -> str:
    """idle | busy | unknown from `launchctl print gui/UID/LABEL`: the service block's own `state`/`pid` fields (one tab
    deep), never a process-name match. A pid, `running` or a launch in progress is busy; only `not running`
    without a pid is idle; anything else, including a missing field, is unknown."""
    lines = text.splitlines()
    if not lines or not lines[0].rstrip().endswith("= {"):
        return "unknown"
    fields: dict[str, str] = {}
    for line in lines[1:]:
        m = _PRINT_FIELD_RE.fullmatch(line.rstrip())
        if m:
            fields.setdefault(m.group(1), m.group(2).strip())
    pid, state = fields.get("pid"), fields.get("state")
    if pid is not None:
        return "busy" if pid.isdigit() and int(pid) > 0 else "unknown"
    if state in ("running", "spawn scheduled", "xpcproxy"):
        return "busy"
    return "idle" if state == "not running" else "unknown"


@contextlib.contextmanager
def _locked_admission_cm(label: str, state_dir: Path | None, env: Mapping[str, str], loaded: bool) -> Iterator[JobAdmission]:
    try:
        fd = acquire_admission_lock(label, exclusive=True, state_dir=state_dir, env=env)
    except OSError as exc:
        yield JobAdmission(hold=f"admission lock of {label} unavailable ({exc})")
        return
    if fd is None:
        yield JobAdmission(hold=f"a run of {label} is active (its admission lock is held); deferred, never waited on or killed")
        return
    try:
        yield JobAdmission(all_launch_paths=True, activity="idle", triggers_drained=True, locked=True, loaded=loaded)
    finally:
        release_admission_lock(fd)


def _locked_admission(label: str, state_dir: Path | None, env: Mapping[str, str], *, loaded: bool) -> Any:
    return _locked_admission_cm(label, state_dir, env, loaded)


def launchd_admission(
    *, launchctl: str, uid: int, agents_dir: Path, env: Mapping[str, str],
    provenance: Callable[[ReconcileStep, Path], str | None] | None = None,
    wrapped: Callable[[ReconcileStep, Path, str | None], str | None] | None = None,
    state_dir: Path | None = None,
    run: Runner | None = None,
) -> Callable[[ReconcileStep], contextlib.AbstractContextManager[JobAdmission]]:
    """The native launchd adapter for `reconcile(admission=...)`: it admits only what is provably safe and never mutates.

    A launch exclusion on a LOADED job does not exist from outside it. Probe, macOS 27.2 (2026-11-12): `launchctl disable`
    does not stop a loaded job's StartInterval trigger and `kickstart` still starts it; and an idle read followed by
    `bootout` is two separate launchd operations, so a trigger firing between them would be signalled (review of #619).
    Nor can a check of a plist and the later write be one atomic step against other writers. So the adapter admits only
    the writes that cannot kill or overwrite (executed by `install_launchd_native`, never `bootout`, never a replace):

    1. Removal: always defer. An unlink cannot be compare-and-swap.
    2. Loaded, in any state: defer, nothing touched. (The updater's own busy service keeps its existing refusal.)
    3. Not loaded and nothing at `agents_dir/LABEL.plist` (not even a dangling symlink): admitted; the install creates the
       file exclusively and bootstraps it.
    4. Not loaded and a file exists: admitted only if `provenance(step, plist)` returns None, i.e. it byte-matches the ADE
       render; the install then only bootstraps it. Any other file defers untouched.
    5. `print` failing for any reason other than "could not find service" defers.

    W21c (`wrapped` supplied): a job whose INSTALLED plist provably routes every launch through `bin/ade-job-run`
    (`wrapper_route_problem`), is ledger-owned with a hash-matching file and, when loaded, whose `print` `path =` is that
    plist (`wrapped(step, plist, print_output)` returns None), is admitted for a reload or removal by taking the label's
    admission lock EXCLUSIVE without waiting. A run in flight holds it shared, so the attempt fails: busy, deferred,
    never waited on and never killed. Once acquired no run is active and none can start (the wrapper skips while it is
    held); the lock stays held until the admission context exits, after the whole mutation. Any other loaded job, and
    every removal that is not provably so, keeps #619's deferral.

    Not covered: a writer that changes the unloaded file between our byte-match read and `bootstrap`; a run launchd has
    spawned but whose wrapper has not yet taken the shared lock when the lock is taken (the wrapper has done no work, so
    the unload loses none); and an unloaded job can still be bootstrapped by something outside this contract (a low-level
    `install`, a login): `install_launchd_native` never boots it out and fails or defers instead."""
    runner = run or _run
    domain = f"gui/{uid}"

    def admit(step: ReconcileStep) -> contextlib.AbstractContextManager[JobAdmission]:
        label = step.label
        if not isinstance(label, str) or not LABEL_RE.fullmatch(label):
            return contextlib.nullcontext(JobAdmission())
        plist = agents_dir / f"{label}.plist"
        removal = step.action == "remove"
        if removal and wrapped is None:
            return contextlib.nullcontext(JobAdmission(hold=(
                f"removal of {label} defers: an unlink cannot be compare-and-swap against other writers")))
        rc, out, err_txt = runner([launchctl, "print", f"{domain}/{label}"], env)
        if rc == 0:
            activity = parse_launchd_activity(out)
            if label in UPDATER_LABELS and activity == "busy":
                return contextlib.nullcontext(JobAdmission(all_launch_paths=True, activity="busy", updater_running=True))
            if wrapped is not None:
                why = wrapped(step, plist, out)
                if why is None:
                    return _locked_admission(label, state_dir, env, loaded=True)
                return contextlib.nullcontext(JobAdmission(hold=(
                    f"{label} is loaded (activity {activity}) and not provably wrapper-routed and ADE-owned: {why}; "
                    f"a loaded launchd job defers until its launch path participates in admission")))
            return contextlib.nullcontext(JobAdmission(hold=(
                f"{label} is loaded (activity {activity}); a loaded launchd job defers until its launch path "
                f"participates in admission"
            )))
        if rc != LAUNCHD_NOT_LOADED_RC and "could not find service" not in err_txt.lower():
            return contextlib.nullcontext(JobAdmission(hold=f"launchd state of {label} unreadable (rc={rc})"))
        if removal:
            why = wrapped(step, plist, None) if wrapped is not None else "no wrapper check supplied"
            if why is None:
                return _locked_admission(label, state_dir, env, loaded=False)
            return contextlib.nullcontext(JobAdmission(hold=(
                f"removal of {label} defers: not provably wrapper-routed and ADE-owned ({why})")))
        if os.path.lexists(plist):
            reason = provenance(step, plist) if provenance else "no provenance check supplied"
            if reason is not None:
                return contextlib.nullcontext(JobAdmission(hold=f"{plist} is not provably ADE's: {reason}"))
        return contextlib.nullcontext(JobAdmission(all_launch_paths=True, activity="idle", triggers_drained=True))

    return admit


def plan_reconcile(
    jobs: list[dict[str, Any]],
    retired: list[dict[str, Any]],
    *,
    ledger: Mapping[str, Any],
    live: LiveScan | None = None,
    backend_name: str,
    root: Path,
    ade: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
    names: set[str] | None = None,
    platform_name: str | None = None,
    extra_subst: Mapping[str, str] | None = None,
    **overrides: Any,
) -> list[ReconcileStep]:
    """Plan ADE-scoped systemd/cron/paseo reconcile actions. Never plans unload of foreign/unknown owners."""
    env = os.environ if env is None else env
    live = live or LiveScan(backend_name, ())
    entries = ledger.get("entries") if isinstance(ledger.get("entries"), dict) else {}
    assert isinstance(entries, dict)
    steps: list[ReconcileStep] = []
    expected_labels: dict[str, str] = {}  # label -> logical name
    blocked_names: set[str] = set()  # logical rows blocked this plan: their removals are suppressed
    # ADE-owned ade-sched/paseo rows that carry a label but are not chosen (class optional/offered, chosen = false):
    # label -> (name, owner). An installed label of such a row is not "foreign", and a ledger-owned one is unloaded because
    # it was un-chosen. Dependency/service rows (herdr-server) are not adoptable, so they keep the old silent path.
    unchosen_labels: dict[str, tuple[str, str]] = {
        str(r["label"]): (str(r["name"]), str(r.get("owner") or "?"))
        for r in jobs
        if isinstance(r.get("label"), str) and r.get("label") and not _job_expected(r)
        and r.get("owner") == OWNER_ADE and r.get("kind") in ("ade-sched", "paseo")
    }
    write_ok = backend_name in RECONCILE_WRITE_BACKENDS
    live_ids = live.ids
    # Host + Paseo share LiveScan; Paseo presence must not treat a same-label host job as live.
    paseo_live_ids = {j.id for j in live.jobs if j.backend == "paseo"}

    for n in live.notes:
        steps.append(ReconcileStep("live-scan", "report", OWNER_ADE, n, touch=False, category="job"))

    for row in jobs:
        name = str(row["name"])
        if names is not None and name not in names:
            continue
        owner = str(row.get("owner") or "?")
        kind = str(row.get("kind") or "")
        if not _job_expected(row):
            steps.append(ReconcileStep(
                name, "skip", owner,
                f"{kind} not chosen; reconcile quiet",
            ))
            continue
        if not _platform_ok(row, platform_name=platform_name):
            steps.append(ReconcileStep(
                name, "skip", owner,
                f"platforms={row.get('platforms')}; not for this host",
            ))
            continue
        prior_entry = entries.get(name)
        desired_backend = "paseo" if kind == "paseo" else backend_name
        if (owner == OWNER_ADE and kind in ("ade-sched", "paseo")
                and isinstance(prior_entry, dict)
                and prior_entry.get("backend") != desired_backend):
            steps.append(ReconcileStep(
                name, "defer", owner,
                f"backend migration {prior_entry.get('backend')} -> {desired_backend}; "
                "preserve old identity until old-backend drain and verified absence",
                label=str(row.get("label") or name),
            ))
            continue
        if kind == "service":
            steps.append(ReconcileStep(
                name, "report", owner,
                "service owner path; ADE reconcile never reimplements (never unload)",
            ))
            continue
        if kind == "paseo":
            if owner != OWNER_ADE:
                steps.append(ReconcileStep(
                    name, "report", owner,
                    "non-ADE owner; report only (never unload)",
                ))
                continue
            label = row.get("label")
            if not isinstance(label, str) or not label:
                steps.append(ReconcileStep(
                    name, "blocked", owner,
                    "paseo schedule missing label/--name",
                ))
                continue
            mode = row.get("mode")
            if not isinstance(mode, str) or not mode:
                steps.append(ReconcileStep(
                    name, "blocked", owner,
                    "paseo schedule requires --mode (refused)",
                    label=label,
                ))
                continue
            expected_labels[label] = name
            entry = entries.get(name) if isinstance(entries.get(name), dict) else None
            if label in paseo_live_ids:
                ledger_match = (
                    isinstance(entry, dict)
                    and entry.get("status") in ("committed", "installed")
                    and entry.get("label") == label
                    and entry.get("backend") == "paseo"
                )
                if ledger_match:
                    steps.append(ReconcileStep(
                        name, "skip", owner,
                        f"paseo schedule {label} present (ledger ok)",
                        label=label,
                    ))
                else:
                    steps.append(ReconcileStep(
                        name, "adopt-ledger", owner,
                        f"paseo schedule {label} live; write ownership ledger (no create)",
                        label=label,
                        touch=True,
                    ))
                continue
            try:
                paseo_schedule_create_argv(row, ade=ade if ade is not None else root, env=env)
            except SchedError as e:
                steps.append(ReconcileStep(
                    name, "blocked", owner,
                    f"paseo create blocked: {e}",
                    label=label,
                ))
                continue
            steps.append(ReconcileStep(
                name, "install", owner,
                f"paseo schedule create {label}",
                label=label,
                touch=True,
            ))
            continue
        if kind != "ade-sched":
            steps.append(ReconcileStep(name, "report", owner, f"kind={kind!r} not reconciled here"))
            continue
        if owner != OWNER_ADE:
            steps.append(ReconcileStep(
                name, "report", owner,
                "non-ADE owner; report only (never unload)",
            ))
            continue
        label = row.get("label")
        plist = row.get("plist")
        if not isinstance(label, str) or not label or not isinstance(plist, str) or not plist:
            steps.append(ReconcileStep(
                name, "planned", owner,
                row.get("notes") or "no label/plist yet; inventory only",
            ))
            continue
        expected_labels[label] = name
        if not write_ok:
            steps.append(ReconcileStep(
                name, "refuse-backend", owner,
                f"reconcile write backends are {sorted(RECONCILE_WRITE_BACKENDS)}; backend={backend_name}",
                label=label,
            ))
            continue
        plist_path = (root / plist).resolve()
        if not plist_path.is_file():
            blocked_names.add(name)
            steps.append(ReconcileStep(
                name, "blocked", owner,
                f"plist missing: {plist}",
                label=label,
            ))
            continue
        try:
            subst = job_subst_from_row(row, root=root, env=env, extra=extra_subst)
            # Preserve ade=None (implicit checkout): Job.from_* only refuses linked worktrees when ade is unset.
            job = Job.from_plist(plist_path, subst, ade=ade)
            rendered = render(job, backend_name, env=env, **overrides)
        except SchedError as e:
            blocked_names.add(name)
            steps.append(ReconcileStep(
                name, "blocked", owner,
                f"render failed: {e}",
                label=label,
            ))
            continue
        if job.label != label:
            blocked_names.add(name)
            steps.append(ReconcileStep(
                name, "blocked", owner,
                f"catalog label {label!r} differs from the plist Label {job.label!r}",
                label=label,
            ))
            continue
        want_hash = artifact_hash(rendered.files)
        entry = entries.get(name) if isinstance(entries.get(name), dict) else None
        st = status(label, backend_name, env=env, **overrides)
        on_disk_match = bool(
            st.installed
            and _on_disk_files_match(
                rendered,
                backend_name=backend_name,
                label=label,
                env=env,
                overrides=overrides,
            )
        )
        ledger_match = (
            isinstance(entry, dict)
            and entry.get("status") in ("committed", "installed")
            and entry.get("artifact_hash") == want_hash
            and entry.get("label") == label
            and entry.get("backend") == backend_name
        )
        expects_timer = _expects_timer(rendered)
        active_ok = _unit_active_ok(
            st, expects_timer=expects_timer, backend_name=backend_name,
        )
        if on_disk_match and ledger_match and active_ok:
            steps.append(ReconcileStep(
                name, "skip", owner,
                f"label {label} healthy (hash match; no reload)",
                label=label,
            ))
            continue
        if on_disk_match and not ledger_match and active_ok:
            # Files match ADE render but ledger lacks committed ownership: record without reload.
            steps.append(ReconcileStep(
                name, "adopt-ledger", owner,
                f"label {label} units match ADE render; write ownership ledger (no reload)",
                label=label,
                touch=True,
            ))
            continue
        if on_disk_match and not active_ok:
            if backend_name == "launchd":
                detail = f"load inactive LaunchAgent {label} (plist match; hash ok)"
            else:
                detail = (
                    f"activate inactive timer {label} (units match; hash ok)"
                    if st.installed else
                    f"install missing label {label} from {plist}"
                )
        else:
            detail = (
                f"install/reload label {label} from {plist}"
                if st.installed else
                f"install missing label {label} from {plist}"
            )
        steps.append(ReconcileStep(
            name, "install", owner, detail, label=label, touch=True,
        ))

    retired_patterns: list[tuple[str, str, str]] = []  # name, owner, pattern
    for row in retired:
        name = str(row["name"])
        if names is not None and name not in names:
            continue
        owner = str(row.get("owner") or "?")
        pattern = str(row.get("label") or "")
        retired_patterns.append((name, owner, pattern))

    # Removals: only labels ADE recorded in the ledger, and only when retired or dropped.
    # Also remove a preserved prior_identity when the logical name's label changed.

    def _plan_remove(logical_id: str, entry: Mapping[str, Any], *, label: str) -> None:
        owner = str(entry.get("owner") or "?")
        if any(s.name == logical_id and s.action == "defer" for s in steps):
            return  # Backend migration retains the old identity without unloading it.
        if owner != OWNER_ADE:
            steps.append(ReconcileStep(
                logical_id, "report", owner,
                f"ledger entry owner={owner}; never unload",
                label=label,
                category="ledger",
            ))
            return
        entry_backend = entry.get("backend")
        paseo_entry = entry_backend == "paseo"
        # Paseo ledger rows are orthogonal to the host backend; systemd/cron rows must match.
        if (
            not paseo_entry
            and isinstance(entry_backend, str)
            and entry_backend
            and entry_backend != backend_name
        ):
            steps.append(ReconcileStep(
                logical_id, "report", owner,
                f"ledger backend={entry_backend!r}; refuse remove on {backend_name} "
                f"(reconcile with that backend to unload {label})",
                label=label,
                category="ledger",
            ))
            return
        is_retired = any(_label_matches(pat, label) for _, _, pat in retired_patterns if pat)
        dropped = not is_retired
        if not _ledger_owns(entry, label=label):
            steps.append(ReconcileStep(
                logical_id, "report", owner,
                f"ledger status={entry.get('status')!r} is not removal authority for {label} "
                f"(intent alone never removes; report only)",
                label=label,
                category="ledger",
            ))
            return
        if not paseo_entry and not write_ok:
            steps.append(ReconcileStep(
                logical_id, "refuse-backend", owner,
                f"would remove ledger-owned {label} but write backends are {sorted(RECONCILE_WRITE_BACKENDS)}; backend={backend_name}",
                label=label,
                category="ledger",
            ))
            return
        why = "retired" if is_retired else ("dropped from inventory" if dropped else "orphan")
        if not is_retired and unchosen_labels.get(label, ("",))[0] == logical_id:
            why = f"inventory row {unchosen_labels[label][0]!r} is not chosen; set chosen = true to keep it"
        detail = (
            f"paseo schedule delete {label} ({why})"
            if paseo_entry else
            f"unload ledger-owned label {label} ({why})"
        )
        steps.append(ReconcileStep(
            logical_id, "remove", owner,
            detail,
            label=label,
            touch=True,
            category="retired" if is_retired else "ledger",
            ledger_snapshot=dict(entry),
        ))

    for logical_id, entry in sorted(entries.items()):
        if names is not None and logical_id not in names:
            continue
        if not isinstance(entry, dict):
            continue
        if logical_id in blocked_names:
            # A blocked row (missing or unrenderable source, label mismatch) keeps its current AND prior identities:
            # removing the last valid definition because its replacement is broken would leave nothing running.
            continue
        label = entry.get("label")
        if isinstance(label, str) and label and label not in expected_labels:
            _plan_remove(logical_id, entry, label=label)
        prior = _prior_identity(entry)
        if prior is not None:
            prior_label = prior.get("label")
            if (
                isinstance(prior_label, str)
                and prior_label
                and prior_label not in expected_labels
                and not any(s.action == "remove" and s.label == prior_label for s in steps)
            ):
                _plan_remove(logical_id, prior, label=prior_label)

    # Retired live but not ledger-owned: report only (never unload).
    for name, owner, pattern in retired_patterns:
        if names is not None and name not in names:
            continue
        hits = sorted(i for i in live_ids if _label_matches(pattern, i))
        if not hits:
            continue
        for hit in hits:
            # Skip if we already planned a ledger-owned remove for this label.
            if any(s.action == "remove" and s.label == hit for s in steps):
                continue
            steps.append(ReconcileStep(
                name, "report", owner,
                f"retired label still live: {hit} (not in ADE ownership ledger; never unload)",
                label=hit,
                category="retired",
            ))

    # Foreign live labels: report only.
    inventory_labels: set[str] = set(expected_labels)
    for _name, _owner, pattern in retired_patterns:
        inventory_labels.add(pattern)
    known_exact = {lab for lab in inventory_labels if not any(ch in lab for ch in "*?[")}
    for lj in live.jobs:
        if lj.source == "non-regular":   # not a live identity; the scan note already reports it
            continue
        if lj.id in known_exact:
            continue
        if any(_label_matches(pat, lj.id) for pat in inventory_labels):
            continue
        if any(s.label == lj.id for s in steps):
            continue
        if lj.id in unchosen_labels:
            uname, uowner = unchosen_labels[lj.id]
            steps.append(ReconcileStep(
                uname, "report", uowner,
                f"live label {lj.id} is installed but inventory row {uname!r} is not chosen "
                f"(report only; not unloaded without ledger ownership; set chosen = true to adopt it)",
                label=lj.id,
                category="job",
            ))
            continue
        if not _foreign_candidate(lj.id) and lj.source != "generated":
            continue
        steps.append(ReconcileStep(
            lj.id, "report", "unknown",
            f"live {lj.backend}/{lj.source} label not ADE-owned (report only; never unload)",
            label=lj.id,
            category="foreign",
        ))
    return steps


def _entry_for_install(
    *,
    name: str,
    label: str,
    backend: str,
    paths: list[str],
    artifact: str,
    generation: int,
    status: str,
    detail: str | None = None,
) -> dict[str, Any]:
    row: dict[str, Any] = {
        "logical_id": name,
        "label": label,
        "owner": OWNER_ADE,
        "backend": backend,
        "scope": "user",
        "paths": paths,
        "artifact_hash": artifact,
        "generation": generation,
        "status": status,
        "updated_at": _utc_now(),
    }
    if detail:
        row["detail"] = detail
    return row


def reconcile(
    jobs: list[dict[str, Any]],
    retired: list[dict[str, Any]],
    *,
    dry_run: bool = True,
    backend: str | Backend | None = None,
    root: Path | None = None,
    ade: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
    state_dir: Path | None = None,
    names: set[str] | None = None,
    live: LiveScan | None = None,
    allow_no_linger: bool = False,
    activate: bool = True,
    platform_name: str | None = None,
    extra_subst: Mapping[str, str] | None = None,
    paseo_run: Callable[[list[str]], subprocess.CompletedProcess[str]] | None = None,
    out: TextIO | None = None,
    err: TextIO | None = None,
    admission: Callable[[ReconcileStep], Any] | None = None,
    native_admission: bool = False,
    **overrides: Any,
) -> tuple[list[dict[str, Any]], int]:
    """Reconcile ADE-owned ade-sched and paseo jobs; write the ownership ledger.

    Default is dry-run (plan only). ``dry_run=False`` executes installs/removes for
    ADE ledger scope only. Never unloads foreign/unknown owners. Never touches root
    / ``--system`` units. Host write backends: systemd user timers, user crontab, and
    launchd LaunchAgents (``RECONCILE_WRITE_BACKENDS``). Paseo schedule create/delete
    is orthogonal (ledger ``backend="paseo"``) and does not require a host write
    backend.

    ``native_admission=True`` (the ade-sched CLI and ``ade-install apply`` set it) installs the read-only launchd
    adapter (``launchd_admission``) when no explicit ``admission`` is given, the backend is launchd and activation is on:
    absent or provably-ADE unloaded jobs are admitted, loaded jobs defer unless wrapper-routed and provably ADE's (W21c: reload/removal under the label's exclusive admission lock); every other case keeps the conservative default.

    Exit 0 when the plan is clean (dry-run) or every touch succeeded; 1 on a failed
    mutation or blocked step; 6 when work is durably deferred; 2 when ``--yes`` refuses host writes on a non-write
    backend (planned ``refuse-backend`` counted even alongside paseo work).
    """
    out = out or sys.stdout
    err = err or sys.stderr
    env = os.environ if env is None else env
    root = Path(root or REPO)
    state_dir = state_dir or jobs_state_dir(env)
    ade_eff = ade if ade is not None else root
    run_paseo = paseo_run or _default_paseo_run

    def _step_targets_paseo(step: ReconcileStep) -> bool:
        if step.action == "remove":
            snap = step.ledger_snapshot
            return isinstance(snap, dict) and snap.get("backend") == "paseo"
        job_row = next((j for j in jobs if j.get("name") == step.name), None)
        return isinstance(job_row, dict) and job_row.get("kind") == "paseo"

    try:
        b = detect(backend, env=env) if not isinstance(backend, Backend) else backend
    except SchedError as e:
        return ([{
            "name": "backend",
            "action": "blocked",
            "owner": OWNER_ADE,
            "detail": str(e),
            "touch": False,
            "ok": False,
        }], EX_UNAVAILABLE if e.code == EX_UNAVAILABLE else EX_USAGE)

    native_install = False  # True: installs go through install_launchd_native (create-exclusive + bootstrap, no bootout)
    if admission is None and native_admission and b.name == "launchd" and activate:
        native_install = True
        # The one native adapter (launchd); systemd/cron/paseo keep the conservative default. An explicit
        # `admission` always wins, and no environment or CLI switch reaches this branch.
        nc = _ctx(b, env, overrides)

        def plist_provenance(step: ReconcileStep, plist: Path) -> str | None:
            """None only when the file on disk is a regular file that byte-matches the ADE render (then it is bootstrapped,
            never written). A ledger hash is not enough: it could not stop a replacement between check and write."""
            try:
                if not stat.S_ISREG(os.lstat(plist).st_mode):
                    return "not a regular file"
                disk_hash = artifact_hash({plist: read_regular_bytes(plist).decode("utf-8")})
            except (OSError, UnicodeDecodeError) as exc:
                return f"unreadable ({exc})"
            job_row = next((j for j in jobs if j.get("name") == step.name), None)
            if isinstance(job_row, dict) and isinstance(job_row.get("plist"), str):
                try:
                    subst = job_subst_from_row(job_row, root=root, env=env, extra=extra_subst)
                    job = Job.from_plist(root / str(job_row["plist"]), subst, ade=ade)
                    if artifact_hash(render(job, b, env=env, **overrides).files) == disk_hash:
                        return None
                except SchedError:
                    pass
            return "exists and does not byte-match the ADE render"

        def wrapped_provenance(step: ReconcileStep, plist: Path, print_out: str | None) -> str | None:
            """None only when a reload/removal of this job may take its exclusive admission lock (W21c): the INSTALLED bytes
            route every launch through bin/ade-job-run, the ledger row is ADE's (committed for a reload; committed or
            pending-remove, or the snapshot, for a removal) with the artifact hash of those very bytes, and, for a loaded job,
            `launchctl print` says it was loaded from this plist."""
            label = step.label
            if not isinstance(label, str):
                return "no label"
            if print_out is not None:
                loaded_from = parse_launchd_path(print_out)
                if loaded_from != str(plist):
                    return f"it was loaded from {loaded_from!r}, not {plist}"
            try:
                data = read_regular_bytes(plist)
                disk_hash = artifact_hash({plist: data.decode("utf-8")})
            except FileNotFoundError:
                if step.action == "remove" and print_out is None:
                    # Unloaded and no file: the removal already happened (an interrupted run); only the ledger row is left.
                    gone = _removal_entry(entries, step.name, label, snapshot=step.ledger_snapshot)
                    if gone is not None and _ledger_owns(gone, label=label) and gone.get("backend") == "launchd":
                        return None
                return f"no plist at {plist}"
            except (OSError, UnicodeDecodeError) as exc:
                return f"{plist} unreadable ({exc})"
            lock_dir = admission_dir(state_dir, env=env)
            why = wrapper_route_problem(data, label, lock_dir=lock_dir)
            if why is not None:
                return why
            program: str | None
            if print_out is not None:   # the LOADED definition is the proof: its lock directory and program (F1, F2 of #622)
                why = loaded_definition_problem(print_out, data, label, lock_dir=lock_dir)
                if why is not None:
                    return why
                program = parse_launchd_definition(print_out)[0]
            else:
                program = plistlib.loads(data)["ProgramArguments"][0]
            why = wrapper_identity_problem(program, ade_root_of(ade))
            if why is not None:
                return why
            if step.action == "remove":
                entry = _removal_entry(entries, step.name, label, snapshot=step.ledger_snapshot)
            else:
                cur = entries.get(step.name)
                entry = cur if isinstance(cur, dict) and cur.get("status") in ("committed", "installed") else None
            if not _ledger_owns(entry, label=label) or entry is None:
                return "no ADE ledger ownership of this label"
            if entry.get("backend") != "launchd" or entry.get("artifact_hash") != disk_hash:
                return "the installed bytes are not the ledger's artifact"
            return None

        launchd_native = launchd_admission(
            launchctl=nc.launchctl, uid=nc.uid, agents_dir=nc.agents_dir, env=nc.env, provenance=plist_provenance,
            wrapped=wrapped_provenance, state_dir=state_dir,
        )

        def admission(step: ReconcileStep) -> Any:  # noqa: F811 - the resolved adapter
            if _step_targets_paseo(step):
                return contextlib.nullcontext(JobAdmission())
            return launchd_native(step)

    if live is None:
        try:
            live = scan_live(b, env=env, skip_paseo=False, paseo_run=paseo_run, **overrides)
        except SchedError as e:
            live = LiveScan(b.name, (), (f"backend scan: {e}",))

    ledger = load_jobs_ledger(state_dir, env=env)

    def _owns_label(label: str) -> bool:
        """Recovery acts only on a label some ADE launchd ledger row (any status, or its prior identity) names."""
        for ent in (ledger.get("entries") or {}).values():
            for cand in (ent, _prior_identity(ent) if isinstance(ent, dict) else None):
                if (isinstance(cand, dict) and cand.get("label") == label and cand.get("owner") == OWNER_ADE
                        and cand.get("backend") == "launchd"):
                    return True
        return False

    steps = plan_reconcile(
        jobs,
        retired,
        ledger=ledger,
        live=live,
        backend_name=b.name,
        root=root,
        ade=ade,
        env=env,
        names=names,
        platform_name=platform_name,
        extra_subst=extra_subst,
        **overrides,
    )

    results: list[dict[str, Any]] = []
    if dry_run:
        if native_install:
            results.extend(recover_launchd_records(state_dir=state_dir, env=env, dry_run=True, owns=_owns_label, **overrides))
        for step in steps:
            row = {
                "name": step.name,
                "action": f"would-{step.action}" if step.touch else step.action,
                "owner": step.owner,
                "label": step.label,
                "detail": step.detail,
                "category": step.category,
                "touch": step.touch,
                "ok": step.action not in ("blocked", "defer"),
            }
            results.append(row)
        # dry-run: blocked inventory rows fail the command; refuse-backend alone is informational
        rc = (1 if any(r["action"] in ("blocked", "failed") for r in results)
              else 6 if any(r["action"] == "defer" for r in results) else 0)
        return results, rc

    # --yes path. Host writes are refused per planned refuse-backend / touch steps when the
    # host backend is not in RECONCILE_WRITE_BACKENDS; paseo touches remain orthogonal.
    # Do not blanket-refuse when the plan is already clean (skip/report only): that made
    # idempotent paseo --yes on launchd exit 2 (Codex P2 on #513).
    write_ok = b.name in RECONCILE_WRITE_BACKENDS

    failed = 0
    refused_host = 0
    mutated = False
    deferred = False
    with _ReconcileLock(reconcile_lock_path(state_dir, env=env)):
        # Reload under the lock so a concurrent writer cannot race removal authority.
        ledger = load_jobs_ledger(state_dir, env=env)
        steps = plan_reconcile(
            jobs,
            retired,
            ledger=ledger,
            live=live,
            backend_name=b.name,
            root=root,
            ade=ade,
            env=env,
            names=names,
            platform_name=platform_name,
            extra_subst=extra_subst,
            **overrides,
        )
        generation = int(ledger.get("generation") or 0) + 1
        entries: dict[str, Any] = dict(ledger.get("entries") or {})

        deferrals_path = state_dir / "jobs-deferred.json"
        if deferrals_path.exists():
            try:
                deferrals = json.loads(deferrals_path.read_text(encoding="utf-8"))
                if not isinstance(deferrals, dict) or not isinstance(deferrals.get("jobs"), dict):
                    raise ValueError("invalid deferral record")
                if not all(isinstance(v, dict) for v in deferrals["jobs"].values()):
                    raise ValueError("invalid per-job deferral record")
            except (OSError, ValueError) as exc:
                raise SchedError(EX_USAGE, f"unreadable deferrals: {exc}") from exc
        else:
            deferrals = {"schema_version": 1, "jobs": {}}
        deferred_names: set[str] = set()

        if native_install:
            # An interrupted locked reload/removal left the job unloaded with a durable record: load it first.
            for rec_row in recover_launchd_records(state_dir=state_dir, env=env, owns=_owns_label, **overrides):
                fix = rec_row.pop("ledger_fix", None)
                if isinstance(fix, dict) and fix.get("drop"):
                    for nm, ent in list(entries.items()):
                        if isinstance(ent, dict) and ent.get("label") == fix["label"] and ent.get("status") == "pending-remove":
                            entries.pop(nm)
                        elif isinstance(ent, dict) and _prior_identity(ent) and ent["prior_identity"].get("label") == fix["label"]:
                            entries[nm] = {k: v for k, v in ent.items() if k != "prior_identity"}
                    ledger["entries"] = entries
                    save_jobs_ledger(ledger, state_dir, env=env)
                elif isinstance(fix, dict):
                    for nm, ent in list(entries.items()):
                        if isinstance(ent, dict) and ent.get("label") == fix["label"] and ent.get("status") != "committed":
                            entries[nm] = {**ent, "status": "committed", "updated_at": _utc_now(),
                                           "detail": "recovered after an interrupted reload",
                                           **({"artifact_hash": fix["artifact_hash"]} if fix.get("artifact_hash") else {})}
                            ledger["entries"] = entries
                            save_jobs_ledger(ledger, state_dir, env=env)
                results.append(rec_row)
                if not rec_row["ok"]:
                    failed += 1

        # Removals first so a label rename keeps the old ledger identity until unload completes.
        ordered_steps = (
            [s for s in steps if s.action == "remove"]
            + [s for s in steps if s.action != "remove"]
        )

        def record_deferral(step: ReconcileStep, reason: str, previous: Any) -> None:
            nonlocal deferred
            deferred = True
            deferred_names.add(step.name)
            target_backend = "paseo" if _step_targets_paseo(step) else b.name
            key = json.dumps([step.name, target_backend, step.label, step.action])
            deferrals["jobs"][key] = {
                "logical_id": step.name, "backend": target_backend, "label": step.label,
                "action": step.action, "reason": reason, "updated_at": _utc_now(),
                "prior_identity": previous,
            }
            _atomic_write_json(deferrals_path, deferrals)

        for step in ordered_steps:
            with contextlib.ExitStack() as admissions:
                row: dict[str, Any] = {
                    "name": step.name,
                    "action": step.action,
                    "owner": step.owner,
                    "label": step.label,
                    "detail": step.detail,
                    "category": step.category,
                    "touch": step.touch,
                    "ok": True,
                }
                reason = step.detail if step.action == "defer" else None
                previous = entries.get(step.name)
                # A missing label in a stale/incomplete scan is no absence proof.
                # Even an initial systemd install may remove a cron trigger.
                disruptive = step.action in ("install", "remove")
                evidence: Any = None
                if step.name in deferred_names:
                    reason = "earlier operation for this logical job deferred"
                elif disruptive:
                    # The context must retain shared admission until after read-back
                    # and ownership commit. A single idle-fleet snapshot is insufficient.
                    evidence = admissions.enter_context(
                        admission(step) if admission else contextlib.nullcontext(JobAdmission())
                    )
                    reason = (evidence.refusal() if isinstance(evidence, JobAdmission)
                              else "unknown shared admission evidence")
                if reason is not None:
                    record_deferral(step, reason, previous)
                    row.update(action="deferred", detail=reason, touch=False, ok=False)
                    results.append(row)
                    continue
                if not step.touch:
                    if step.action == "blocked":
                        row["ok"] = False
                        failed += 1
                    elif step.action == "refuse-backend":
                        # Planned host refuse (touch=False): still exit 2 when mixed with paseo
                        # work (Codex P2 on #513).
                        row["ok"] = False
                        refused_host += 1
                    results.append(row)
                    continue

                label = step.label
                assert isinstance(label, str)
                is_paseo = _step_targets_paseo(step)
                if not is_paseo and not write_ok:
                    row["action"] = "refuse-backend"
                    row["ok"] = False
                    row["touch"] = False
                    row["detail"] = step.detail or (
                        f"reconcile write backends are {sorted(RECONCILE_WRITE_BACKENDS)}; "
                        f"backend={b.name}"
                    )
                    refused_host += 1
                    results.append(row)
                    continue

                if step.action == "adopt-ledger":
                    job_row = next((j for j in jobs if j.get("name") == step.name), None)
                    if is_paseo:
                        if not isinstance(job_row, dict):
                            row["ok"] = False
                            row["action"] = "failed"
                            row["detail"] = "adopt-ledger missing paseo catalog row"
                            failed += 1
                            results.append(row)
                            continue
                        try:
                            ah = paseo_artifact_hash(job_row, ade=ade_eff, env=env)
                        except SchedError:
                            # Live schedule may predate create-field inventory; still adopt ownership.
                            ah = hashlib.sha256(f"paseo:{label}".encode()).hexdigest()
                        prev = entries.get(step.name) if isinstance(entries.get(step.name), dict) else None
                        entries[step.name] = _with_prior_identity(
                            _entry_for_install(
                                name=step.name,
                                label=label,
                                backend="paseo",
                                paths=[f"paseo-schedule:{label}"],
                                artifact=ah,
                                generation=generation,
                                status="committed",
                                detail="adopted existing paseo schedule",
                            ),
                            prev if isinstance(prev, dict) else None,
                            new_label=label,
                        )
                        mutated = True
                        row["action"] = "adopted"
                        results.append(row)
                        continue
                    if not isinstance(job_row, dict) or not isinstance(job_row.get("plist"), str):
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = "adopt-ledger missing catalog plist"
                        failed += 1
                        results.append(row)
                        continue
                    try:
                        subst = job_subst_from_row(job_row, root=root, env=env, extra=extra_subst)
                        job = Job.from_plist(root / str(job_row["plist"]), subst, ade=ade)
                        rendered = render(job, b, env=env, **overrides)
                        ah = artifact_hash(rendered.files)
                    except SchedError as e:
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = str(e)
                        failed += 1
                        results.append(row)
                        continue
                    prev = entries.get(step.name) if isinstance(entries.get(step.name), dict) else None
                    entries[step.name] = _with_prior_identity(
                        _entry_for_install(
                            name=step.name,
                            label=label,
                            backend=b.name,
                            paths=[str(p) for p in rendered.files],
                            artifact=ah,
                            generation=generation,
                            status="committed",
                            detail="adopted existing matching units",
                        ),
                        prev if isinstance(prev, dict) else None,
                        new_label=label,
                    )
                    mutated = True
                    row["action"] = "adopted"
                    results.append(row)
                    continue

                if step.action == "install":
                    job_row = next((j for j in jobs if j.get("name") == step.name), None)
                    if is_paseo:
                        if not isinstance(job_row, dict):
                            row["ok"] = False
                            row["action"] = "failed"
                            row["detail"] = "install missing paseo catalog row"
                            failed += 1
                            results.append(row)
                            continue
                        try:
                            argv = paseo_schedule_create_argv(job_row, ade=ade_eff, env=env)
                            ah = paseo_artifact_hash(job_row, ade=ade_eff, env=env)
                        except SchedError as e:
                            row["ok"] = False
                            row["action"] = "failed"
                            row["detail"] = str(e)
                            failed += 1
                            results.append(row)
                            continue
                        prev = entries.get(step.name) if isinstance(entries.get(step.name), dict) else None
                        entries[step.name] = _with_prior_identity(
                            _entry_for_install(
                                name=step.name,
                                label=label,
                                backend="paseo",
                                paths=[f"paseo-schedule:{label}"],
                                artifact=ah,
                                generation=generation,
                                status="pending",
                            ),
                            prev if isinstance(prev, dict) else None,
                            new_label=label,
                        )
                        ledger["entries"] = entries
                        ledger["generation"] = generation
                        save_jobs_ledger(ledger, state_dir, env=env)
                        try:
                            proc = run_paseo(argv)
                            if proc.returncode != 0:
                                detail = (proc.stderr or proc.stdout or "").strip() or f"rc={proc.returncode}"
                                raise SchedError(EX_ACTIVATE, f"paseo schedule create failed: {detail}")
                            live_jobs, ls_notes = paseo_schedule_names(run=run_paseo)
                            if ls_notes:
                                raise SchedError(
                                    EX_ACTIVATE,
                                    f"read-back: paseo schedule ls failed after create: {ls_notes[0]}",
                                )
                            if label not in {lj.id for lj in live_jobs}:
                                raise SchedError(EX_ACTIVATE, f"read-back: paseo schedule {label} not listed after create")
                        except SchedError as e:
                            entries[step.name] = _with_prior_identity(
                                _entry_for_install(
                                    name=step.name,
                                    label=label,
                                    backend="paseo",
                                    paths=[f"paseo-schedule:{label}"],
                                    artifact=ah,
                                    generation=generation,
                                    status="failed",
                                    detail=str(e),
                                ),
                                prev if isinstance(prev, dict) else None,
                                new_label=label,
                            )
                            ledger["entries"] = entries
                            save_jobs_ledger(ledger, state_dir, env=env)
                            row["ok"] = False
                            row["action"] = "failed"
                            row["detail"] = str(e)
                            failed += 1
                            results.append(row)
                            continue
                        except (OSError, subprocess.TimeoutExpired) as e:
                            entries[step.name] = _with_prior_identity(
                                _entry_for_install(
                                    name=step.name,
                                    label=label,
                                    backend="paseo",
                                    paths=[f"paseo-schedule:{label}"],
                                    artifact=ah,
                                    generation=generation,
                                    status="failed",
                                    detail=str(e),
                                ),
                                prev if isinstance(prev, dict) else None,
                                new_label=label,
                            )
                            ledger["entries"] = entries
                            save_jobs_ledger(ledger, state_dir, env=env)
                            row["ok"] = False
                            row["action"] = "failed"
                            row["detail"] = str(e)
                            failed += 1
                            results.append(row)
                            continue
                        committed = _entry_for_install(
                            name=step.name,
                            label=label,
                            backend="paseo",
                            paths=[f"paseo-schedule:{label}"],
                            artifact=ah,
                            generation=generation,
                            status="committed",
                        )
                        cur = entries.get(step.name)
                        if isinstance(cur, dict) and _prior_identity(cur) is not None:
                            committed = {**committed, "prior_identity": cur["prior_identity"]}
                        else:
                            committed = _with_prior_identity(
                                committed, prev if isinstance(prev, dict) else None, new_label=label,
                            )
                        entries[step.name] = committed
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        mutated = True
                        row["action"] = "installed"
                        results.append(row)
                        continue

                    if not isinstance(job_row, dict) or not isinstance(job_row.get("plist"), str):
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = "install missing catalog plist"
                        failed += 1
                        results.append(row)
                        continue
                    try:
                        subst = job_subst_from_row(job_row, root=root, env=env, extra=extra_subst)
                        job = Job.from_plist(root / str(job_row["plist"]), subst, ade=ade)
                        rendered = render(job, b, env=env, **overrides)
                        ah = artifact_hash(rendered.files)
                    except SchedError as e:
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = str(e)
                        failed += 1
                        results.append(row)
                        continue
                    prev = entries.get(step.name) if isinstance(entries.get(step.name), dict) else None
                    # Pending intent before any host write (setup-plan contract 4).
                    entries[step.name] = _with_prior_identity(
                        _entry_for_install(
                            name=step.name,
                            label=label,
                            backend=b.name,
                            paths=[str(p) for p in rendered.files],
                            artifact=ah,
                            generation=generation,
                            status="pending",
                        ),
                        prev if isinstance(prev, dict) else None,
                        new_label=label,
                    )
                    ledger["entries"] = entries
                    ledger["generation"] = generation
                    save_jobs_ledger(ledger, state_dir, env=env)
                    try:
                        if job.label != label:
                            raise SchedError(
                                EX_USAGE,
                                f"catalog label {label!r} differs from the plist Label {job.label!r}; "
                                f"refusing to act on an unadmitted label",
                            )
                        if native_install:
                            try:
                                if isinstance(evidence, JobAdmission) and evidence.locked and evidence.loaded:
                                    reload_launchd_locked(   # under the exclusive admission lock `evidence` holds
                                        job, next(iter(rendered.files.values())), state_dir=state_dir, env=env,
                                        expect_hash=(prev or {}).get("artifact_hash"), **overrides,
                                    )
                                else:
                                    install_launchd_native(
                                        job, next(iter(rendered.files.values())), env=env, err=err,
                                        state_dir=state_dir, **overrides,
                                    )
                            except (OSError, ValueError) as exc:  # mkdir/link/chmod/encode: a failed row, not a traceback
                                raise SchedError(EX_ACTIVATE, f"native launchd install of {label} failed: {exc}") from exc
                        else:
                            install(
                                job, b, dry_run=False, activate=activate,
                                allow_no_linger=allow_no_linger, env=env, out=out, err=err,
                                **overrides,
                            )
                        st = status(label, b, env=env, **overrides)
                        if not st.installed:
                            raise SchedError(EX_ACTIVATE, f"read-back: {label} not installed after install")
                    except NativeDefer as e:
                        # No launchd definition was written: put the ledger row back as it was and defer (exit 6), never "failed".
                        if prev is None:
                            entries.pop(step.name, None)
                        else:
                            entries[step.name] = prev
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        reason = str(e)
                        record_deferral(step, reason, prev)
                        row.update(action="deferred", detail=reason, touch=False, ok=False)
                        results.append(row)
                        continue
                    except (KeyboardInterrupt, SystemExit):
                        if isinstance(evidence, JobAdmission) and evidence.locked and evidence.loaded:
                            # An interrupt in the locked reload (after a rollback or before the unload): the prior
                            # definition is what is loaded, so the ledger keeps its old row.
                            if prev is None:
                                entries.pop(step.name, None)
                            else:
                                entries[step.name] = prev
                            ledger["entries"] = entries
                            save_jobs_ledger(ledger, state_dir, env=env)
                        raise
                    except ReloadRolledBack as e:
                        # The job is loaded again with its PRIOR definition: the ledger keeps owning it (committed), the run fails.
                        if prev is None:
                            entries.pop(step.name, None)
                        else:
                            entries[step.name] = prev
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        row.update(ok=False, action="failed", detail=str(e))
                        failed += 1
                        results.append(row)
                        continue
                    except SchedError as e:
                        entries[step.name] = _with_prior_identity(
                            _entry_for_install(
                                name=step.name,
                                label=label,
                                backend=b.name,
                                paths=[str(p) for p in rendered.files],
                                artifact=ah,
                                generation=generation,
                                status="failed",
                                detail=str(e),
                            ),
                            prev if isinstance(prev, dict) else None,
                            new_label=label,
                        )
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = str(e)
                        failed += 1
                        results.append(row)
                        continue
                    committed = _entry_for_install(
                        name=step.name,
                        label=label,
                        backend=b.name,
                        paths=[str(p) for p in st.paths] if st.paths else [str(p) for p in rendered.files],
                        artifact=ah,
                        generation=generation,
                        status="committed",
                    )
                    # Preserve prior_identity across pending -> committed if remove has not cleared it yet.
                    cur = entries.get(step.name)
                    if isinstance(cur, dict) and _prior_identity(cur) is not None:
                        committed = {**committed, "prior_identity": cur["prior_identity"]}
                    else:
                        committed = _with_prior_identity(
                            committed, prev if isinstance(prev, dict) else None, new_label=label,
                        )
                    entries[step.name] = committed
                    ledger["entries"] = entries
                    save_jobs_ledger(ledger, state_dir, env=env)
                    mutated = True
                    row["action"] = "installed"
                    results.append(row)
                    continue

                if step.action == "remove":
                    entry = _removal_entry(
                        entries, step.name, label, snapshot=step.ledger_snapshot,
                    )
                    if entry is None:
                        row["ok"] = False
                        row["action"] = "report"
                        row["detail"] = (
                            f"refusing remove of {label}: missing/invalid ledger ownership"
                        )
                        row["touch"] = False
                        # Not a hard failure of the run: safety refusal.
                        results.append(row)
                        continue
                    entry_backend = entry.get("backend")
                    paseo_entry = entry_backend == "paseo"
                    if (
                        not paseo_entry
                        and isinstance(entry_backend, str)
                        and entry_backend
                        and entry_backend != b.name
                    ):
                        row["ok"] = False
                        row["action"] = "report"
                        row["detail"] = (
                            f"refusing remove of {label}: ledger backend={entry_backend!r}; "
                            f"reconcile backend={b.name}"
                        )
                        row["touch"] = False
                        results.append(row)
                        continue
                    before_remove = entries.get(step.name)
                    live_entry = entries.get(step.name)
                    if isinstance(live_entry, dict) and live_entry.get("label") == label:
                        entries[step.name] = {
                            **live_entry,
                            "status": "pending-remove",
                            "updated_at": _utc_now(),
                            "generation": generation,
                        }
                    elif isinstance(live_entry, dict) and _prior_identity(live_entry) is not None:
                        # New label already claimed this logical_id; mark only the preserved identity.
                        prior = dict(live_entry["prior_identity"])
                        prior["status"] = "pending-remove"
                        prior["updated_at"] = _utc_now()
                        prior["generation"] = generation
                        entries[step.name] = {**live_entry, "prior_identity": prior}
                    ledger["entries"] = entries
                    ledger["generation"] = generation
                    save_jobs_ledger(ledger, state_dir, env=env)
                    try:
                        if paseo_entry:
                            argv = paseo_schedule_delete_argv(label)
                            proc = run_paseo(argv)
                            if proc.returncode != 0:
                                detail = (proc.stderr or proc.stdout or "").strip() or f"rc={proc.returncode}"
                                raise SchedError(EX_ACTIVATE, f"paseo schedule delete failed: {detail}")
                            live_jobs, ls_notes = paseo_schedule_names(run=run_paseo)
                            if ls_notes:
                                raise SchedError(
                                    EX_ACTIVATE,
                                    f"read-back: paseo schedule ls failed after delete: {ls_notes[0]}",
                                )
                            if label in {lj.id for lj in live_jobs}:
                                raise SchedError(EX_ACTIVATE, f"read-back: paseo schedule {label} still listed after delete")
                        else:
                            if isinstance(evidence, JobAdmission) and evidence.locked:
                                remove_launchd_locked(   # under the exclusive admission lock `evidence` holds
                                    label, expect_hash=str(entry.get("artifact_hash")), loaded=evidence.loaded,
                                    state_dir=state_dir, env=env, **overrides,
                                )
                            else:
                                uninstall(label, b, dry_run=False, activate=activate, env=env, out=out, err=err, **overrides)
                            st = status(label, b, env=env, **overrides)
                            if st.installed:
                                raise SchedError(EX_ACTIVATE, f"read-back: {label} still installed after uninstall")
                            if b.name == "launchd" and activate and st.active:
                                raise SchedError(
                                    EX_ACTIVATE,
                                    f"read-back: launchd {label} still loaded after uninstall",
                                )
                    except NativeDefer as e:
                        # Nothing was removed or unloaded: put the ledger row back as it was and defer (exit 6).
                        if before_remove is None:
                            entries.pop(step.name, None)
                        else:
                            entries[step.name] = before_remove
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        reason = str(e)
                        record_deferral(step, reason, before_remove)
                        row.update(action="deferred", detail=reason, touch=False, ok=False)
                        results.append(row)
                        continue
                    except (SchedError, OSError, subprocess.TimeoutExpired) as e:
                        # Keep pending-remove so the next reconcile retries; "failed" alone
                        # would drop _ledger_owns and leave a surviving schedule forever.
                        live_entry = entries.get(step.name)
                        if isinstance(live_entry, dict) and live_entry.get("label") == label:
                            entries[step.name] = {
                                **entry,
                                "status": "pending-remove",
                                "detail": str(e),
                                "updated_at": _utc_now(),
                                "generation": generation,
                            }
                        elif isinstance(live_entry, dict) and _prior_identity(live_entry) is not None:
                            prior = dict(entry)
                            prior["status"] = "pending-remove"
                            prior["detail"] = str(e)
                            prior["updated_at"] = _utc_now()
                            prior["generation"] = generation
                            entries[step.name] = {**live_entry, "prior_identity": prior}
                        ledger["entries"] = entries
                        save_jobs_ledger(ledger, state_dir, env=env)
                        row["ok"] = False
                        row["action"] = "failed"
                        row["detail"] = str(e)
                        failed += 1
                        results.append(row)
                        continue
                    live_entry = entries.get(step.name)
                    if isinstance(live_entry, dict) and live_entry.get("label") == label:
                        entries.pop(step.name, None)
                    elif isinstance(live_entry, dict) and _prior_identity(live_entry) is not None:
                        cleared = dict(live_entry)
                        cleared.pop("prior_identity", None)
                        entries[step.name] = cleared
                    ledger["entries"] = entries
                    save_jobs_ledger(ledger, state_dir, env=env)
                    mutated = True
                    row["action"] = "removed"
                    results.append(row)
                    continue

                results.append(row)

        completed_names = {r["name"] for r in results
                           if r["action"] in ("installed", "removed", "adopted")}
        resolved = {key: value for key, value in deferrals["jobs"].items()
                    if value.get("logical_id") not in completed_names
                    or value.get("logical_id") in deferred_names}
        if resolved != deferrals["jobs"]:
            deferrals["jobs"] = resolved
            _atomic_write_json(deferrals_path, deferrals)

        if mutated and not failed:
            ledger["generation"] = generation
            ledger["entries"] = entries
            save_jobs_ledger(ledger, state_dir, env=env)

    if refused_host and not failed:
        return results, EX_USAGE
    return results, (1 if failed else (6 if deferred else 0))
