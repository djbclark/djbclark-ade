def load_jobs_ledger(
    state_dir: Path | None = None,
    *,
    env: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    """Load ``jobs.json``. Missing file → empty ledger. Unreadable/invalid → SchedError (fail closed on removal)."""
    path = jobs_ledger_path(state_dir, env=env)
    if not path.is_file():
        return empty_jobs_ledger(env=env)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, RecursionError) as e:
        raise SchedError(EX_USAGE, f"{path}: unreadable jobs ledger ({e})") from e
    if not isinstance(raw, dict):
        raise SchedError(EX_USAGE, f"{path}: jobs ledger root must be an object")
    entries = raw.get("entries")
    if entries is None:
        entries = {}
    if not isinstance(entries, dict):
        raise SchedError(EX_USAGE, f"{path}: entries must be an object")
    # Reject unknown top-level shapes that would make removal authority unclear.
    for key, entry in entries.items():
        if not isinstance(key, str) or not isinstance(entry, dict):
            raise SchedError(EX_USAGE, f"{path}: entries[{key!r}] must be an object")
    out = empty_jobs_ledger(env=env)
    out["schema_version"] = int(raw.get("schema_version") or JOBS_LEDGER_SCHEMA_VERSION)
    out["generation"] = int(raw.get("generation") or 0)
    out["updated_at"] = raw.get("updated_at")
    out["host"] = raw.get("host") or out["host"]
    out["user"] = raw.get("user") or out["user"]
    out["entries"] = entries
    return out


