_UNREADABLE: Any = object()   # sentinel: the entry vanished or cannot be read; the scan skips it
_NON_REGULAR: Any = object()  # sentinel: a FIFO, socket, device or directory; reported, never opened
_HEAD_BYTES = 4096


def _read_regular(path: Path, limit: int) -> Any:
    """Up to `limit` bytes of a regular file without ever blocking on it (B1, 2026-11-13).

    A FIFO (or a symlink to one) planted among the `*.plist` files used to hang `reconcile`, because `read_text` opens
    it for reading and waits for a writer. Now: `lstat` (and `stat` for a symlink) must say regular file before any
    open; the open is `O_NONBLOCK|O_NOCTTY` (plus `O_NOFOLLOW` unless the entry is a symlink to a regular file, which the
    scan has always followed) and `fstat` on the descriptor must say regular again, closing the lstat-to-open race. The
    read is bounded. Returns the bytes, `_NON_REGULAR` for an entry that is not a regular file (never opened past the
    check) or `_UNREADABLE`."""
    try:
        lst = os.lstat(path)
        is_link = stat.S_ISLNK(lst.st_mode)
        st = os.stat(path) if is_link else lst
    except OSError:
        return _UNREADABLE
    if not stat.S_ISREG(st.st_mode):
        return _NON_REGULAR
    flags = os.O_RDONLY | os.O_NONBLOCK | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOCTTY", 0)
    if not is_link:
        flags |= getattr(os, "O_NOFOLLOW", 0)
    try:
        fd = os.open(path, flags)
    except OSError:
        return _UNREADABLE
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            return _NON_REGULAR
        return os.read(fd, limit)
    except OSError:
        return _UNREADABLE
    finally:
        os.close(fd)


def _unit_head(path: Path) -> Any:
    """First 4 KiB of a unit/plist file as text for the live scan: `_read_regular`'s result decoded, or its sentinel."""
    raw = _read_regular(path, _HEAD_BYTES)
    return raw if raw is _NON_REGULAR or raw is _UNREADABLE else raw.decode("utf-8", errors="replace")[:_HEAD_BYTES]


def read_regular_bytes(path: Path, limit: int = 1 << 20) -> bytes:
    """A whole (bounded) regular file for reconcile's byte-match checks: OSError for anything not a regular file."""
    raw = _read_regular(path, limit + 1)
    if raw is _NON_REGULAR:
        raise OSError(f"{path} is not a regular file")
    if raw is _UNREADABLE:
        if not os.path.lexists(path):
            raise FileNotFoundError(f"{path} does not exist")
        raise OSError(f"{path} is unreadable")
    if len(raw) > limit:
        raise OSError(f"{path} is larger than {limit} bytes")
    return raw


def list_backend_labels(backend: str | Backend | None = None, *, env: Mapping[str, str] | None = None,
                        **overrides: Any) -> list[LiveJob]:
    """All on-disk labels for the active backend (ade-sched generated and sibling unit/plist files)."""
    c = _ctx(backend, env, overrides)
    name = c.backend.name
    out: list[LiveJob] = []
    if name == "cron":
        try:
            text = _crontab_read(c)
        except SchedError as e:
            raise SchedError(e.code, f"crontab read for scan: {e}") from e
        for ln in text.splitlines():
            if ln.startswith("# BEGIN ade-sched:"):
                label = ln[len("# BEGIN ade-sched:"):].strip()
                if label:
                    out.append(LiveJob(label, "cron", "crontab", True))
        return out
    if name == "launchd":
        d = c.agents_dir
        if d.is_dir():
            for p in sorted(d.glob("*.plist")):
                head = _unit_head(p)
                if head is _UNREADABLE:
                    continue
                if head is _NON_REGULAR:
                    out.append(LiveJob(p.stem, "launchd", "non-regular", None))
                    continue
                src = "generated" if GENERATED in head else "file"
                st = status(p.stem, c.backend, env=c.env, agents_dir=c.agents_dir, launchctl=c.launchctl)
                out.append(LiveJob(p.stem, "launchd", src, st.active if st.installed else False))
        return out
    # systemd
    d = c.units
    if d.is_dir():
        for p in sorted(d.glob("*.service")):
            head = _unit_head(p)
            if head is _UNREADABLE:
                continue
            if head is _NON_REGULAR:
                out.append(LiveJob(p.stem, "systemd", "non-regular", None))
                continue
            src = "generated" if GENERATED in head else "file"
            st = status(p.stem, c.backend, env=c.env, unit_dir=c.units, systemctl=c.systemctl)
            out.append(LiveJob(p.stem, "systemd", src, st.active if st.installed else False))
    return out


def paseo_schedule_names(
    *,
    run: Callable[[list[str]], subprocess.CompletedProcess[str]] | None = None,
    which: Callable[[str], str | None] = shutil.which,
) -> tuple[list[LiveJob], tuple[str, ...]]:
    """Names from `paseo schedule ls --json`. Missing/unavailable paseo is a note, not an error."""
    notes: list[str] = []
    if run is None:
        if which("paseo") is None:
            return [], ("paseo not on PATH; paseo schedules not probed",)

        def run(argv: list[str]) -> subprocess.CompletedProcess[str]:
            return subprocess.run(  # noqa: S603 — argv list only
                argv, capture_output=True, text=True, check=False, timeout=30,
            )

    try:
        proc = run(["paseo", "schedule", "ls", "--json"])
    except subprocess.TimeoutExpired:
        notes.append("paseo schedule ls failed (timeout)")
        return [], tuple(notes)
    except OSError as e:
        # FileNotFoundError and other launch failures: treat as unavailable, never traceback.
        notes.append(f"paseo schedule ls failed (launch: {e})")
        return [], tuple(notes)
    if proc.returncode != 0:
        notes.append(f"paseo schedule ls failed (rc={proc.returncode})")
        return [], tuple(notes)
    text = (proc.stdout or "").strip()
    if not text:
        return [], tuple(notes)
    try:
        data = json.loads(text)
    except ValueError:
        notes.append("paseo schedule ls: invalid JSON")
        return [], tuple(notes)
    rows = data if isinstance(data, list) else data.get("schedules") or data.get("items") or []
    if not isinstance(rows, list):
        notes.append("paseo schedule ls: unexpected JSON shape")
        return [], tuple(notes)
    out: list[LiveJob] = []
    for row in rows:
        if isinstance(row, str):
            out.append(LiveJob(row, "paseo", "paseo", True))
            continue
        if not isinstance(row, dict):
            continue
        name = row.get("name") or row.get("Name") or row.get("id") or row.get("Id")
        if isinstance(name, str) and name:
            out.append(LiveJob(name, "paseo", "paseo", True))
    return out, tuple(notes)


def paseo_schedule_create_argv(
    row: Mapping[str, Any],
    *,
    ade: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
) -> list[str]:
    """Build ``paseo schedule create`` argv from an inventory row (docs/scheduling.md).

    Requires schedule, mode, provider, cwd, prompt; timezone from the row or ``ADE_TIMEZONE``.
    Fills ``__ADE__`` / ``__HOME__`` (and @ forms) in cwd and prompt. Relative cwd resolves
    against the ADE checkout.
    """
    env = os.environ if env is None else env
    label = row.get("label")
    if not isinstance(label, str) or not label:
        raise SchedError(EX_USAGE, "paseo schedule create requires label/--name")
    mode = row.get("mode")
    if not isinstance(mode, str) or not mode:
        raise SchedError(EX_USAGE, "paseo schedule create requires --mode")
    schedule = row.get("schedule")
    if not isinstance(schedule, str) or not schedule:
        raise SchedError(EX_USAGE, "paseo schedule create requires schedule/--cron")
    tz = row.get("timezone")
    if not isinstance(tz, str) or not tz.strip():
        tz = (env.get("ADE_TIMEZONE") or "").strip()
    if not tz:
        raise SchedError(
            EX_USAGE,
            "paseo schedule create requires timezone (inventory timezone= or ADE_TIMEZONE)",
        )
    provider = row.get("provider")
    if not isinstance(provider, str) or not provider:
        raise SchedError(EX_USAGE, "paseo schedule create requires provider")
    cwd_raw = row.get("cwd")
    if not isinstance(cwd_raw, str) or not cwd_raw:
        raise SchedError(EX_USAGE, "paseo schedule create requires cwd")
    prompt_raw = row.get("prompt")
    if not isinstance(prompt_raw, str) or not prompt_raw:
        raise SchedError(EX_USAGE, "paseo schedule create requires prompt")
    subst = default_subst(ade=ade, env=env)
    cwd = cwd_raw
    prompt = prompt_raw
    for key, val in sorted(subst.items(), key=lambda kv: -len(kv[0])):
        cwd = cwd.replace(key, val)
        prompt = prompt.replace(key, val)
    cwd_path = Path(cwd).expanduser()
    if not cwd_path.is_absolute():
        root = Path(os.path.realpath(ade) if ade else str(REPO))
        cwd_path = (root / cwd_path).resolve()
    else:
        cwd_path = cwd_path.resolve()
    return [
        "paseo", "schedule", "create",
        "--cron", schedule,
        "--timezone", tz,
        "--name", label,
        "--mode", mode,
        "--provider", provider,
        "--cwd", str(cwd_path),
        prompt,
    ]


def paseo_schedule_delete_argv(name: str) -> list[str]:
    """Build ``paseo schedule delete --name NAME`` (matches create's ``--name``; CLI shape documented in docs/scheduling.md)."""
    if not isinstance(name, str) or not name:
        raise SchedError(EX_USAGE, "paseo schedule delete requires --name")
    return ["paseo", "schedule", "delete", "--name", name]


def paseo_artifact_hash(
    row: Mapping[str, Any],
    *,
    ade: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
) -> str:
    """Stable hash of the create argv identity for ledger artifact_hash."""
    argv = paseo_schedule_create_argv(row, ade=ade, env=env)
    return hashlib.sha256("\0".join(argv).encode()).hexdigest()


