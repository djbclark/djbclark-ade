"""ade_sched: install a launchd plist as a launchd agent, a systemd user unit or a crontab block (issue #279, 2026-11-04).

Imported by bin/ade-sched and by the job installers (they run under `python3 -I`, so each puts this directory on sys.path
first, the way bin/claude-quota-guard does for ade_gates.py). Not a program. Stdlib only. docs/scheduling.md is the manual.

The checked-in plists (launchd/, config/launchd/) stay the source of truth. A job is read from one of them, its placeholders
(`__ADE__`, `__HOME__`, `__STATE__`, `@TARGET@`, ...) filled into the PARSED dict (never into the XML text), and then:

  launchd  the filled plist is written to ~/Library/LaunchAgents/LABEL.plist and bootstrapped into gui/UID
  systemd  LABEL.service (+ LABEL.timer) in the user unit dir, daemon-reload, enable, restart
  cron     a `# BEGIN ade-sched:LABEL` .. `# END ade-sched:LABEL` block in the user's crontab (foreign lines kept)

Public API (every function takes an optional `env` mapping, default os.environ: it holds the overrides and is the base of
every child's environment):

  default_subst(ade=None, env=None) -> dict          __ADE__/@ADE@ (the checkout) and __HOME__/@HOME@
  Job.from_plist(path, subst=None, *, ade=None, kill_mode=None) -> Job      parse, fill, validate (SchedError 2)
  Job.from_dict(d, source="<dict>", subst=None, *, ade=None, kill_mode=None) -> Job
  detect(backend=None, env=None, platform=None, which=shutil.which, run=None, booted_dir=..., run_user_dir=..., uid=None,
         exists=os.path.exists) -> Backend(name, env, reason)
  render(job, backend, env=None, **overrides) -> Rendered(backend, files, notes, activation, cron_block)
  install(job, backend=None, *, dry_run=False, activate=True, allow_no_linger=False, env=None, out=None, err=None,
          **overrides) -> Rendered
  uninstall(label, backend=None, *, dry_run=False, activate=True, env=None, out=None, err=None, **overrides) -> bool
  status(label, backend=None, *, env=None, **overrides) -> Status(backend, label, installed, active, next_run, paths)
  installed_labels(backend=None, *, env=None, **overrides) -> list[str]
  linger(env=None, **overrides) -> "yes" | "no" | None
  systemd_version(env=None, **overrides) -> int | None

  overrides (keyword): agents_dir, unit_dir, launchctl, systemctl, loginctl, crontab, lock_path. A caller passes its own
  older override (ACP_DISPATCH_LAUNCHCTL, *_LAUNCH_AGENTS) through these; they beat the ADE_SCHED_* env variables.

Errors raise SchedError with .code: 1 an activation command failed (its stderr quoted; also `crontab -l` failing for any
reason but "no crontab", so a crontab is never rewritten from a bad read), 2 a bad job or usage (also: a secret-looking
environment variable name, or __ADE__ defaulted into a linked git worktree on install), 69 no usable scheduler (forced
`none`, nothing found, the systemd user manager unreachable, linger off on a systemd install, KeepAlive or a sub-minute
StartInterval on cron).
"""
